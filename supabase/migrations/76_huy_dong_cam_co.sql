CREATE OR REPLACE FUNCTION public.save_pledge_loan(p_loan jsonb, p_links jsonb)
RETURNS bigint
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_id       bigint := nullif(p_loan->>'Id', '')::bigint;
  v_customer bigint := (p_loan->>'CustomerId')::bigint;
  v_amount   numeric := (p_loan->>'Amount')::numeric;
  v_link     jsonb;
  v_book     record;
  v_sum      numeric := 0;
  v_old      record;
BEGIN
  IF p_links IS NULL OR jsonb_typeof(p_links) <> 'array' OR jsonb_array_length(p_links) = 0 THEN
    RAISE EXCEPTION 'Khoản vay cầm cố phải gắn ít nhất một sổ tiết kiệm';
  END IF;

  FOR v_link IN SELECT * FROM jsonb_array_elements(p_links) LOOP
    SELECT "Id", "BookNumber", "CustomerId", "IsClosed" INTO v_book
      FROM "SavingsBooks" WHERE "Id" = (v_link->>'SavingsBookId')::bigint;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Không tìm thấy sổ tiết kiệm %', v_link->>'SavingsBookId';
    END IF;
    IF v_book."CustomerId" <> v_customer THEN
      RAISE EXCEPTION 'Sổ % không thuộc khách hàng của khoản vay', v_book."BookNumber";
    END IF;
    IF v_book."IsClosed" THEN
      RAISE EXCEPTION 'Sổ % đã tất toán', v_book."BookNumber";
    END IF;
    v_sum := v_sum + coalesce((v_link->>'PrincipalCovered')::numeric, 0);
  END LOOP;

  IF v_sum <> v_amount THEN
    RAISE EXCEPTION 'Tổng phần gốc bảo đảm (%) phải bằng số tiền vay (%)', v_sum, v_amount;
  END IF;

  IF v_id IS NULL THEN
    INSERT INTO "PledgeLoans" ("CustomerId", "ContractNumber", "Amount", "InterestRate", "DisbursementDate", "DueDate", "LoanPurpose", "Note")
    VALUES (v_customer, btrim(p_loan->>'ContractNumber'), v_amount, (p_loan->>'InterestRate')::numeric,
            (p_loan->>'DisbursementDate')::date, (p_loan->>'DueDate')::date, p_loan->>'LoanPurpose', p_loan->>'Note')
    RETURNING "Id" INTO v_id;
  ELSE
    SELECT * INTO v_old FROM "PledgeLoans" WHERE "Id" = v_id FOR UPDATE;
    IF FOUND AND EXISTS (SELECT 1 FROM "PledgeLoanRepayments" WHERE "PledgeLoanId" = v_id)
       AND (v_old."Amount" <> v_amount OR v_old."DisbursementDate" <> (p_loan->>'DisbursementDate')::date) THEN
      RAISE EXCEPTION 'Khoản vay % đã có lần trả nợ: không sửa được số tiền vay và ngày giải ngân', v_old."ContractNumber";
    END IF;
    UPDATE "PledgeLoans" SET
      "ContractNumber"   = btrim(p_loan->>'ContractNumber'),
      "Amount"           = v_amount,
      "InterestRate"     = (p_loan->>'InterestRate')::numeric,
      "DisbursementDate" = (p_loan->>'DisbursementDate')::date,
      "DueDate"          = (p_loan->>'DueDate')::date,
      "LoanPurpose"      = p_loan->>'LoanPurpose',
      "Note"             = p_loan->>'Note'
    WHERE "Id" = v_id AND "CustomerId" = v_customer AND NOT "IsClosed";
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Không sửa được khoản vay %: không tìm thấy hoặc đã tất toán', v_id;
    END IF;
    DELETE FROM "PledgeLoanSavingsBooks" WHERE "PledgeLoanId" = v_id AND "ReleasedDate" IS NULL;
  END IF;

  INSERT INTO "PledgeLoanSavingsBooks" ("PledgeLoanId", "SavingsBookId", "PrincipalCovered")
  SELECT v_id, (l->>'SavingsBookId')::bigint, (l->>'PrincipalCovered')::numeric
  FROM jsonb_array_elements(p_links) AS l;

  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.record_pledge_repayment(p_loan_id bigint, p_repayment jsonb, p_book_closing_interest numeric)
RETURNS bigint
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_loan        record;
  v_kind        text    := p_repayment->>'Kind';
  v_date        date    := (p_repayment->>'RepaymentDate')::date;
  v_principal   numeric := coalesce((p_repayment->>'PrincipalPaid')::numeric, 0);
  v_book_id     bigint  := nullif(p_repayment->>'OffsetSavingsBookId', '')::bigint;
  v_outstanding numeric;
  v_last        date;
  v_id          bigint;
BEGIN
  SELECT * INTO v_loan FROM "PledgeLoans" WHERE "Id" = p_loan_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Không tìm thấy khoản vay %', p_loan_id;
  END IF;
  IF v_loan."IsClosed" THEN
    RAISE EXCEPTION 'Khoản vay đã tất toán';
  END IF;

  SELECT v_loan."Amount" - coalesce(sum("PrincipalPaid"), 0), greatest(v_loan."DisbursementDate", max("RepaymentDate"))
    INTO v_outstanding, v_last
    FROM "PledgeLoanRepayments" WHERE "PledgeLoanId" = p_loan_id;

  IF v_kind = 'due' THEN
    v_date := v_loan."DueDate";
  END IF;
  IF v_date IS NULL OR v_date < v_last THEN
    RAISE EXCEPTION 'Ngày trả phải từ ngày % trở đi', v_last;
  END IF;

  IF v_kind = 'partial' THEN
    IF v_principal <= 0 OR v_principal >= v_outstanding THEN
      RAISE EXCEPTION 'Gốc trả trước một phần phải lớn hơn 0 và nhỏ hơn dư nợ (%)', v_outstanding;
    END IF;
  ELSIF v_principal <> v_outstanding THEN
    RAISE EXCEPTION 'Tất toán khoản vay phải trả hết dư nợ (%)', v_outstanding;
  END IF;

  IF v_kind = 'offset' THEN
    IF v_book_id IS NULL OR NOT EXISTS (
      SELECT 1 FROM "PledgeLoanSavingsBooks"
      WHERE "PledgeLoanId" = p_loan_id AND "SavingsBookId" = v_book_id AND "ReleasedDate" IS NULL
    ) THEN
      RAISE EXCEPTION 'Sổ tất toán để cấn trừ phải là sổ đang bảo đảm cho khoản vay';
    END IF;
    IF EXISTS (SELECT 1 FROM "SavingsBooks" WHERE "Id" = v_book_id AND "IsClosed" FOR UPDATE) THEN
      RAISE EXCEPTION 'Sổ đã tất toán, không cấn trừ lần nữa được';
    END IF;
  END IF;

  INSERT INTO "PledgeLoanRepayments" ("PledgeLoanId", "RepaymentDate", "Kind", "PrincipalPaid", "InterestPaid", "PenaltyPaid", "OffsetSavingsBookId", "Note")
  VALUES (p_loan_id, v_date, v_kind, v_principal,
          coalesce((p_repayment->>'InterestPaid')::numeric, 0),
          coalesce((p_repayment->>'PenaltyPaid')::numeric, 0),
          v_book_id, p_repayment->>'Note')
  RETURNING "Id" INTO v_id;

  IF v_kind <> 'partial' THEN
    UPDATE "PledgeLoans" SET "IsClosed" = true, "ClosedDate" = v_date, "ClosedHow" = v_kind WHERE "Id" = p_loan_id;
    UPDATE "PledgeLoanSavingsBooks" SET "ReleasedDate" = v_date WHERE "PledgeLoanId" = p_loan_id AND "ReleasedDate" IS NULL;
  END IF;

  IF v_kind = 'offset' THEN
    UPDATE "SavingsBooks" SET "IsClosed" = true, "ClosedDate" = v_date, "ClosingInterest" = p_book_closing_interest
    WHERE "Id" = v_book_id;
  END IF;

  RETURN v_id;
END;
$$;

