export interface Signature {
  name: string;
  args: string[];
}

export const FUNCTION_SIGNATURES: ReadonlyMap<string, Signature> = new Map(
  SIGNATURES.split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line): [string, Signature] => {
      const open = line.indexOf('(');
      const name = line.slice(0, open);
      const inside = line.slice(open + 1, line.lastIndexOf(')')).trim();
      return [name, { name, args: inside === '' ? [] : inside.split(',').map((arg) => arg.trim()) }];
    }),
);
