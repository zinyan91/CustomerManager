-- Hợp đồng thẻ: thay bảng CreditCards bằng CardContracts + CardSupplementaryHolders.
--
-- VÌ SAO BẢNG RIÊNG, KHÔNG NHÉT VÀO CreditContracts: trường của hợp đồng thẻ khác
-- HĐTD gần hết — loại thẻ, chủ thẻ (KH hay vợ/chồng), mã chính sách phát hành,
-- chủ thẻ phụ, thời hạn cố định 60 tháng. Nhét chung là dựng một bảng nửa rỗng.
--
-- VÌ SAO XOÁ CreditCards: chủ dự án chốt 10/08/2026 — dữ liệu thẻ hiện có ít và
-- sẽ khai lại toàn bộ theo mô hình mới. Bảng cũ không biểu diễn được hợp đồng thẻ
-- (không có số hợp đồng, không có mã chính sách, không có thẻ phụ) và ô "số thẻ"
-- của nó là dữ liệu banker không thể biết lúc lập hồ sơ.
--
-- HẠN MỨC DÙNG CHUNG. Một hợp đồng thẻ có thể phát hành cả Visa, Mastercard và
-- Napas cùng lúc trên CÙNG MỘT hạn mức. Vì vậy hạn mức nằm ở hợp đồng
-- (GrantedLimit), KHÔNG nằm ở từng thẻ — đây là điểm dễ làm sai nhất: lưu theo
-- từng thẻ rồi cộng lại sẽ tiêu tốn khả năng bảo đảm gấp ba lần thực tế.
-- Thẻ phụ cũng đồng mức cấp với thẻ chính nên không cộng thêm.
--
-- THẺ GHI NỢ ATM không có hạn mức tín dụng. Ràng buộc dưới đây chặn việc khai
-- hạn mức cho hợp đồng chỉ có thẻ ghi nợ, và chặn hạn mức 0 cho thẻ tín dụng.
--
-- KH và vợ/chồng là HAI hợp đồng riêng vì hạn mức khác nhau.

BEGIN;

DROP TABLE IF EXISTS "CreditCards" RESTRICT;

CREATE TABLE "CardContracts" (
  "Id"                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "CustomerId"         bigint NOT NULL REFERENCES "Customers"("Id") ON DELETE RESTRICT,
  "CardContractNumber" text   NOT NULL,
  "CardHolderSide"     text   NOT NULL DEFAULT 'KH',
  "CardHolderName"     text,
  "CardProducts"       text,
  "GrantedLimit"       numeric,
  "PolicyCode"         text,
  "CollateralKind"     text,
  "CollateralId"       bigint REFERENCES "Collaterals"("Id") ON DELETE RESTRICT,
  "TenorMonths"        integer NOT NULL DEFAULT 60,
  "IssueDate"          date,
  "ExpiryDate"         date,
  "IsClosed"           boolean NOT NULL DEFAULT false,
  "Note"               text,
  "CreatedAt"          timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT "CardContracts_ChuThe_hop_le"
    CHECK ("CardHolderSide" IN ('KH', 'KHLQ')),

  CONSTRAINT "CardContracts_LoaiTSBD_hop_le"
    CHECK ("CollateralKind" IS NULL
           OR "CollateralKind" IN ('KHONG_TSBD', 'TIEN_GUI', 'CO_TSBD')),

  CONSTRAINT "CardContracts_HanMuc_khong_am"
    CHECK ("GrantedLimit" IS NULL OR "GrantedLimit" >= 0),

  -- Có TSBĐ thật thì phải gán tài sản. Chốt này nằm dưới database vì chốt ở
  -- client không đỡ được đường ghi SQL.
  CONSTRAINT "CardContracts_CoTSBD_phai_gan_tai_san"
    CHECK ("CollateralKind" <> 'CO_TSBD' OR "CollateralId" IS NOT NULL)
);

-- Số hợp đồng thẻ NAT/<năm>/<số thứ tự>. Unique trên dạng chuẩn hoá để
-- 'NAT/2026/001' và 'nat/2026/001 ' là cùng một số chứng từ — cùng cách làm với
-- LoanContracts_ContractNumber_key ở migration 20.
CREATE UNIQUE INDEX "CardContracts_CardContractNumber_key"
  ON "CardContracts" (lower(btrim("CardContractNumber")));

CREATE INDEX "CardContracts_CustomerId_idx" ON "CardContracts" ("CustomerId");

COMMENT ON COLUMN "CardContracts"."GrantedLimit" IS
  'Hạn mức được cấp cho CẢ hợp đồng, dùng chung cho mọi thương hiệu thẻ trong CardProducts và cho mọi thẻ phụ. NULL/0 với thẻ ghi nợ.';
COMMENT ON COLUMN "CardContracts"."CardProducts" IS
  'Danh sách dòng thẻ phát hành trên hợp đồng, ngăn cách bằng dấu chấm phẩy. Một hợp đồng có thể gồm Visa + Mastercard + Napas trên cùng một hạn mức.';
COMMENT ON COLUMN "CardContracts"."PolicyCode" IS
  'KHOÁ BỀN của mã chính sách phát hành thẻ (A1, A2, B1…B13), KHÔNG phải chuỗi mã chính thức dài. Mã chính thức theo văn bản (ví dụ B6_KHCN_KHONG TSBD_THUNHAP_ LUONG QUA VIETBANK) chỉ dùng để hiển thị và có thể đổi khi Phòng Thẻ ban hành quyết định mới; lưu khoá bền để hồ sơ cũ không mồ côi. Nguồn danh mục ở src/lib/cardContract.ts (CARD_POLICIES), luật hạn mức ở src/lib/cardPolicyRules.ts.';


CREATE TABLE "CardSupplementaryHolders" (
  "Id"             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "CardContractId" bigint NOT NULL REFERENCES "CardContracts"("Id") ON DELETE CASCADE,
  "FullName"       text   NOT NULL,
  "Relation"       text   NOT NULL,
  "RelationNote"   text,
  "NationalId"     text,
  "CreatedAt"      timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT "CardSupplementaryHolders_HoTen_khong_rong"
    CHECK (btrim("FullName") <> ''),
  CONSTRAINT "CardSupplementaryHolders_QuanHe_khong_rong"
    CHECK (btrim("Relation") <> '')
);

CREATE INDEX "CardSupplementaryHolders_CardContractId_idx"
  ON "CardSupplementaryHolders" ("CardContractId");

COMMENT ON TABLE "CardSupplementaryHolders" IS
  'Chủ thẻ phụ. Đồng mức cấp với thẻ chính nên KHÔNG có cột hạn mức riêng. Tối đa 2 thẻ phụ mỗi hợp đồng — chốt bằng trigger dưới đây.';

-- Tối đa 2 thẻ phụ mỗi hợp đồng. Không dùng CHECK được vì luật đếm qua nhiều dòng.
CREATE OR REPLACE FUNCTION "fn_chan_qua_hai_the_phu"()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  so_the_phu integer;
BEGIN
  SELECT count(*) INTO so_the_phu
  FROM "CardSupplementaryHolders"
  WHERE "CardContractId" = NEW."CardContractId"
    AND "Id" <> coalesce(NEW."Id", -1);

  IF so_the_phu >= 2 THEN
    RAISE EXCEPTION
      'Một thẻ chính chỉ có tối đa 2 thẻ phụ; hợp đồng thẻ Id=% đã có % thẻ phụ.',
      NEW."CardContractId", so_the_phu;
  END IF;

  RETURN NEW;
END $$;

CREATE TRIGGER "trg_chan_qua_hai_the_phu"
  BEFORE INSERT OR UPDATE ON "CardSupplementaryHolders"
  FOR EACH ROW EXECUTE FUNCTION "fn_chan_qua_hai_the_phu"();


ALTER TABLE "CardContracts"             ENABLE ROW LEVEL SECURITY;
ALTER TABLE "CardSupplementaryHolders"  ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.can_access_card_contract(p_card_contract_id bigint)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public."CardContracts" cc
    WHERE cc."Id" = p_card_contract_id
      AND public.can_access_customer(cc."CustomerId")
  );
$$;

DROP POLICY IF EXISTS "card_contracts_all" ON public."CardContracts";
CREATE POLICY "card_contracts_all" ON public."CardContracts"
  FOR ALL TO authenticated
  USING (public.can_access_customer("CustomerId"))
  WITH CHECK (public.can_access_customer("CustomerId"));

DROP POLICY IF EXISTS "card_supplementary_holders_all" ON public."CardSupplementaryHolders";
CREATE POLICY "card_supplementary_holders_all" ON public."CardSupplementaryHolders"
  FOR ALL TO authenticated
  USING (public.can_access_card_contract("CardContractId"))
  WITH CHECK (public.can_access_card_contract("CardContractId"));

REVOKE ALL ON public."CardContracts"            FROM anon;
REVOKE ALL ON public."CardSupplementaryHolders" FROM anon;

COMMIT;


-- Đối chiếu. Kỳ vọng: CreditCards không còn; hai bảng mới tồn tại, mỗi bảng đúng
-- một policy, RLS đang bật; 0 bảng nào hở RLS.

SELECT
  (SELECT count(*) FROM information_schema.tables
     WHERE table_schema = 'public' AND table_name = 'CreditCards')            AS con_bang_cu,
  (SELECT count(*) FROM information_schema.tables
     WHERE table_schema = 'public'
       AND table_name IN ('CardContracts', 'CardSupplementaryHolders'))       AS so_bang_moi;

SELECT c.relname AS bang, c.relrowsecurity AS rls_bat,
       (SELECT count(*) FROM pg_policies p
          WHERE p.schemaname = 'public' AND p.tablename = c.relname)          AS so_policy
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public'
  AND c.relname IN ('CardContracts', 'CardSupplementaryHolders')
ORDER BY 1;

SELECT c.relname AS bang_ho_rls
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public' AND c.relkind = 'r' AND NOT c.relrowsecurity
ORDER BY 1;
