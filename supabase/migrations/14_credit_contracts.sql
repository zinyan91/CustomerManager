CREATE INDEX IF NOT EXISTS idx_loan_contracts_credit_contract
  ON public."LoanContracts" ("CreditContractId");


-- ---------------------------------------------------------------------
-- 4. DỰNG HĐTD TỪ DỮ LIỆU KUNN HIỆN CÓ
-- ---------------------------------------------------------------------
-- Mỗi nhóm KUNN cùng số HĐTD sinh một hợp đồng. Chọn dòng có tổng mức cấp
-- lớn nhất làm bản gốc, đúng cách computeCreditLimit đang gom nhóm — nếu
-- các dòng trong nhóm đang lệch nhau thì mục 6 in ra để đối chiếu.

INSERT INTO public."CreditContracts" (
  "CustomerId", "HdtdNumber", "ApprovalCode", "ApprovalAmount",
  "LoanMethod", "ContractAmount", "ContractStartDate", "ContractEndDate",
  "LoanTenorMonths", "LoanPurpose", "LoanPurposeType",
  "PreferentialRate", "PreferentialPeriodMonths", "PostPreferentialRate",
  "BaseRate", "MarginRate", "NormalRate", "InterestRate", "RateHistory",
  "CollateralIds", "Note"
)
SELECT DISTINCT ON (g."CustomerId", g.hdtd_no)
  g."CustomerId", g.hdtd_no, g."CreditLimitCode", g."CreditLimitAmount",
  g."LoanMethod", g."ContractAmount", g."ContractStartDate", g."ContractEndDate",
  g."LoanTenorMonths", g."LoanPurpose", g."LoanPurposeType",
  g."PreferentialRate", g."PreferentialPeriodMonths", g."PostPreferentialRate",
  g."BaseRate", g."MarginRate", g."NormalRate", g."InterestRate", g."Note",
  g."CollateralIds",
  'Dựng tự động từ KUNN khi tách bảng HĐTD (migration 14)'
FROM (
  SELECT lc.*, public.hdtd_number_of(lc."ContractNumber", lc."Note") AS hdtd_no
  FROM public."LoanContracts" lc
) g
ORDER BY
  g."CustomerId", g.hdtd_no,
  COALESCE(g."ContractAmount", 0) DESC,
  g."Id" ASC
ON CONFLICT ("CustomerId", "HdtdNumber") DO NOTHING;


UPDATE public."LoanContracts" lc
SET "CreditContractId" = cc."Id"
FROM public."CreditContracts" cc
WHERE cc."CustomerId" = lc."CustomerId"
  AND cc."HdtdNumber" = public.hdtd_number_of(lc."ContractNumber", lc."Note")
  AND lc."CreditContractId" IS NULL;


