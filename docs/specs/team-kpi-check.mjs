import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';

const folder = 'docs/specs/';
const context = vm.createContext({ Intl });
vm.runInContext(fs.readFileSync(folder + 'team-kpi-model.js', 'utf8'), context);
const M = context.TeamKpiModel;
let checks = 0;
const check = (value, message) => { assert.ok(value, message); checks++; };
const state = M.createState();
check(state.month === 9, 'default is the completed September period');
check(M.capabilities(state).team, 'leader sees team');
check(!M.capabilities(state).allocate, 'closed month is read only');

for (const teamId of ['a', 'b']) for (const metric of M.metrics) for (const month of [1, 6, 9, 10]) {
  const current = { ...M.createState(), teamId, metricId: metric.id, month };
  const rows = M.rows(current);
  const total = M.total(current);
  check(total.actual === rows.reduce((sum, row) => sum + row.actual, 0), `${teamId}/${metric.id}/${month}: team actual reconciles`);
  check(total.target === rows.reduce((sum, row) => sum + row.target, 0), `${teamId}/${metric.id}/${month}: allocation reconciles`);
  const monthTotals = Array.from({ length: month }, (_, index) => M.total({ ...current, month: index + 1 }).actual);
  const cumulative = M.total(current, true);
  check(cumulative.actual === (metric.kind === 'stock' ? total.actual : monthTotals.reduce((sum, value) => sum + value, 0)), `${metric.id}: cumulative aggregation`);
}
check(M.completion(12, 0) === null, 'zero target has no completion rate');
check(M.completion(12, null) === null, 'unassigned target differs from zero');
check(M.completion(null, 10) === null, 'missing actual is not zero');
check(M.completion(12, 10) === 120, 'overachievement is not capped at 100%');
check(!M.capabilities({ ...state, role: 'member', month: 10 }).team, 'member cannot access team summary');
check(!M.capabilities({ ...state, role: 'member', month: 10 }).allocate, 'member cannot allocate');
check(!M.capabilities(state).manageTeam, 'leader is not global admin');
check(M.capabilities({ ...state, role: 'admin' }).manageTeam, 'admin may manage team');
check(M.visibleRows({ ...state, role: 'member' }).length === 1, 'member sees only own row');
check(M.series(state).length === 6, 'trend displays six months');
const open = { ...M.createState(), month: 10 };
const allocations = Object.fromEntries(M.rows(open).map(row => [row.member.id, row.target]));
const first = Object.keys(allocations)[0];
allocations[first] -= 1000000;
const saved = M.allocate(open, allocations, 'Điều chỉnh phân bổ tháng 10');
check(saved.ok, 'valid draft allocation saves');
check(M.total(saved.state).target === M.total(open).target, 'allocation does not silently change team target');
check(M.unallocated(saved.state) === 1000000, 'unallocated amount is visible');
check(M.unallocated(open) === 0, 'source state remains unchanged');
check(saved.state.audit.length === 1, 'allocation has audit entry');
check(!M.allocate({ ...open, role: 'member' }, allocations, 'x').ok, 'member write is rejected');
check(!M.allocate(state, allocations, 'x').ok, 'closed period write is rejected');
check(!M.allocate(open, { ...allocations, [first]: -1 }, 'x').ok, 'negative target rejected');
check(!M.allocate(open, { ...allocations, [first]: Number.NaN }, 'x').ok, 'NaN rejected');
check(!M.allocate(open, { ...allocations, [first]: allocations[first] + M.total(open).target }, 'x').ok, 'over-allocation rejected');
check(!M.allocate(open, allocations, '  ').ok, 'reason required');
check(M.rows(state).some(row => row.actual < 0), 'net growth supports negative actuals');
check(M.completion(-5, 10) === -50, 'negative achievement remains negative');
for (const area of ['team', 'personal']) {
  const current = { ...state, area, metricId: 'fees' };
  const actual = area === 'team' ? M.total(current).actual : M.visibleRows(current)[0].actual;
  check(M.feeComponents(current).length === 7, 'seven fee categories from Excel');
  check(M.feeComponents(current).reduce((sum, row) => sum + row.value, 0) === actual, 'fee breakdown reconciles to visible scope');
}

const html = fs.readFileSync(folder + '2026-10-20-team-kpi.html', 'utf8');
const dom = new JSDOM(html, { url: 'http://localhost/team-kpi', runScripts: 'outside-only', pretendToBeVisual: true });
const w = dom.window, d = w.document;
w.HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', ''); };
w.HTMLDialogElement.prototype.close = function () { this.removeAttribute('open'); };
for (const file of ['model', 'views', 'controller']) w.eval(fs.readFileSync(folder + `team-kpi-${file}.js`, 'utf8'));
const change = (id, value) => { d.getElementById(id).value = value; d.getElementById(id).dispatchEvent(new w.Event('change', { bubbles: true })); };
const click = selector => { assert.ok(d.querySelector(selector), selector); d.querySelector(selector).click(); };
check(d.querySelector('h1').textContent.includes('Team'), 'team overview renders');
check(d.querySelectorAll('svg[role="img"]').length === 2, 'both charts have accessible names');
click('[data-view="targets"]');
check(d.querySelector('tbody tr:last-child').textContent.includes('TỔNG CỘNG'), 'total is last table row');
check(!d.querySelector('[data-action="allocate"]'), 'closed month has no edit action');
change('month', '10');
check(Boolean(d.querySelector('[data-action="allocate"]')), 'open month allows allocation');
click('[data-action="allocate"]');
check(d.getElementById('allocation-dialog').open, 'allocation dialog opens');
const form = d.getElementById('allocation-form');
form.querySelector('input').value = String(Number(form.querySelector('input').value) - .001);
form.querySelector('textarea').value = 'Phân bổ thử nghiệm';
form.dispatchEvent(new w.Event('submit', { bubbles: true, cancelable: true }));
check(!d.getElementById('allocation-dialog').open, 'saving closes dialog');
check(d.querySelector('main').textContent.includes('Chưa phân bổ'), 'saved remainder shown in target table');
check(d.querySelector('main').textContent.includes('Phân bổ thử nghiệm'), 'saved allocation audit rendered');
click('[data-action="allocate"]');
click('[data-action="cancel"]');
change('preview-role', 'member');
check(!d.querySelector('[data-area="team"]'), 'team tab hidden for member');
check(d.querySelectorAll('tbody tr[data-member]').length === 1, 'member personal KPI only');
check(!d.querySelector('[data-action="allocate"]'), 'member has no edit action');
check(!d.querySelector('main').textContent.includes('Phân bổ thử nghiệm'), 'member does not see team allocation audit');
change('preview-role', 'leader');
click('[data-area="team"]');
click('[data-view="members"]');
check(d.querySelectorAll('tbody tr[data-member]').length === 5, 'team roster includes leader once');
click('[data-open-member="a3"]');
check(d.querySelector('h1').textContent.includes('Lê Thu Hà'), 'leader opens member RBO by name');
check(d.querySelectorAll('tbody tr[data-member]').length === 1, 'selected member KPI stays scoped');
click('[data-area="team"]');
click('[data-view="score"]');
check(d.querySelector('h2').textContent.includes('SRBO'), 'leader evaluation has separate SRBO view');
check(d.querySelector('main').textContent.includes('Chờ cấu hình'), 'missing score policy not replaced with invented scores');
click('[data-view="members"]');
check(!d.querySelector('[data-action="manage-team"]'), 'leader cannot change team membership');
change('preview-role', 'admin');
check(Boolean(d.getElementById('team')), 'admin team selector');
change('team', 'b');
check(d.querySelector('h1').textContent.includes('B'), 'team switch updates destination');
click('[data-view="targets"]');
check(!d.querySelector('main').textContent.includes('Phân bổ thử nghiệm'), 'team B does not show team A audit');
check(!html.includes('https://'), 'prototype has no external resource dependency');
dom.window.close();
const embeddedDom = new JSDOM(html, { url: 'http://localhost/team-kpi?embedded=1', runScripts: 'outside-only' });
for (const file of ['model', 'views', 'controller']) embeddedDom.window.eval(fs.readFileSync(folder + `team-kpi-${file}.js`, 'utf8'));
check(embeddedDom.window.document.documentElement.classList.contains('embedded'), 'embedded mode removes duplicate shell');
check(embeddedDom.window.document.querySelector('[data-area="personal"]').textContent === 'KPI cá nhân', 'embedded KPI tab differs from existing personal dashboard');
embeddedDom.window.close();
console.log(`${checks} checks passed`);
