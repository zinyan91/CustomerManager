-- =====================================================================
-- Chương trình lãi suất: cho vay ngắn hạn, trung dài hạn và huy động
-- =====================================================================
-- Lãi suất chào khách thay đổi theo từng thời kỳ, do một văn bản của
-- Ban điều hành ban hành và có ngày hiệu lực. Vì vậy KHÔNG cứng hoá
-- con số trong mã nguồn: mỗi kỳ là một dòng trong "RatePrograms",
-- banker tra theo ngày, admin nhập kỳ mới.
--
-- Ba loại chương trình dùng CHUNG một bảng dòng lãi suất
-- ("RateProgramTiers") vì cùng bản chất "một điều kiện -> một mức lãi".
-- Các cột chiều (kỳ hạn, bậc số dư, cách trả lãi, kênh) để NULL ở loại
-- không dùng tới, thay vì nhét vào trường ghi chú.
--
-- An toàn khi chạy lại nhiều lần.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. CHƯƠNG TRÌNH
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."RatePrograms" (
  "Id"             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "Kind"           text    NOT NULL CHECK ("Kind" IN ('cho_vay_ngan_han', 'cho_vay_trung_dai_han', 'huy_dong')),
  "Name"           text    NOT NULL,
  "DocumentNumber" text    NOT NULL UNIQUE,
  "DocumentDate"   date,
  "EffectiveFrom"  date    NOT NULL,
  "EffectiveTo"    date,
  "QuotaVnd"       numeric CHECK ("QuotaVnd" IS NULL OR "QuotaVnd" >= 0),

  -- Lãi suất sau thời gian cố định = lãi suất cơ sở + biên độ tối thiểu.
  "FloatingBaseLabel"    text,
  "FloatingSpreadAnnual" numeric CHECK ("FloatingSpreadAnnual" IS NULL OR "FloatingSpreadAnnual" >= 0),
  "RateResetMonths"      integer CHECK ("RateResetMonths" IS NULL OR "RateResetMonths" > 0),

  "MinFeeAmountVnd"        numeric CHECK ("MinFeeAmountVnd" IS NULL OR "MinFeeAmountVnd" >= 0),
  "NewCustomerFeeDiscount" numeric CHECK ("NewCustomerFeeDiscount" IS NULL OR ("NewCustomerFeeDiscount" >= 0 AND "NewCustomerFeeDiscount" <= 1)),
  "CasaShortfallFeeAddon"  numeric CHECK ("CasaShortfallFeeAddon" IS NULL OR "CasaShortfallFeeAddon" >= 0),
  "CasaMinRatio"           numeric CHECK ("CasaMinRatio" IS NULL OR "CasaMinRatio" >= 0),

  -- Chương trình cấm dùng thẩm quyền giảm lãi/giảm phí thì đánh dấu ở đây,
  -- để công cụ giảm lãi suất cảnh báo thay vì để banker tự nhớ.
  "AllowRateReduction"  boolean NOT NULL DEFAULT true,
  "AllowPrepayFeeWaive" boolean NOT NULL DEFAULT true,

  -- false = số liệu nạp từ bảng tính nội bộ, CHƯA đối chiếu văn bản gốc.
  "SourceVerified" boolean NOT NULL DEFAULT false,
  "Note"           text,
  "CreatedAt"      timestamptz NOT NULL DEFAULT now(),
  "UpdatedAt"      timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT chk_rateprograms_period
    CHECK ("EffectiveTo" IS NULL OR "EffectiveTo" >= "EffectiveFrom")
);

COMMENT ON TABLE public."RatePrograms" IS
  'Chương trình lãi suất theo từng thời kỳ. SourceVerified = false nghĩa là số liệu chưa đối chiếu văn bản gốc, không được dùng để chào khách.';

CREATE INDEX IF NOT EXISTS idx_rateprograms_kind_period
  ON public."RatePrograms" ("Kind", "EffectiveFrom" DESC);


-- ---------------------------------------------------------------------
-- 2. DÒNG LÃI SUẤT
-- ---------------------------------------------------------------------
-- Cho vay: PackageCode (LC1..LC5), FixedMonths, MinTenorMonths, MinFeeRatio.
-- Huy động: Channel, BalanceTierLabel, PayoutMode.
-- RateAnnual để NULL = CHƯA CÓ SỐ, khác hẳn 0 = không tính lãi/miễn phí.

CREATE TABLE IF NOT EXISTS public."RateProgramTiers" (
  "Id"        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ProgramId" integer NOT NULL REFERENCES public."RatePrograms"("Id") ON DELETE CASCADE,

  "PackageCode"    text,
  "Label"          text    NOT NULL,
  "FixedMonths"    integer CHECK ("FixedMonths" IS NULL OR "FixedMonths" > 0),
  "MinTenorMonths" integer CHECK ("MinTenorMonths" IS NULL OR "MinTenorMonths" > 0),
  "MinFeeRatio"    numeric CHECK ("MinFeeRatio" IS NULL OR "MinFeeRatio" >= 0),

  "Channel"          text CHECK ("Channel" IS NULL OR "Channel" IN ('quay', 'online', 'ftp')),
  "BalanceTierLabel" text,
  "PayoutMode"       text CHECK ("PayoutMode" IS NULL OR "PayoutMode" IN ('cuoi_ky', 'hang_thang', 'hang_quy', 'tra_truoc')),
  "TenorMonths"      integer CHECK ("TenorMonths" IS NULL OR "TenorMonths" > 0),

  "RateAnnual" numeric CHECK ("RateAnnual" IS NULL OR ("RateAnnual" >= 0 AND "RateAnnual" <= 1)),
  "SortOrder"  integer NOT NULL DEFAULT 0,
  "Note"       text
);

COMMENT ON COLUMN public."RateProgramTiers"."RateAnnual" IS
  'Dạng thập phân: 0.0845 = 8,45%/năm. NULL nghĩa là chưa có số, KHÔNG phải 0%.';

CREATE INDEX IF NOT EXISTS idx_rateprogramtiers_program
  ON public."RateProgramTiers" ("ProgramId", "SortOrder");


-- ---------------------------------------------------------------------
-- 3. PHÍ TRẢ NỢ TRƯỚC HẠN THEO NĂM
-- ---------------------------------------------------------------------
-- FeeRatio = 0 là MIỄN PHÍ (số liệu đã biết).
-- FeeRatio IS NULL là CHƯA CÓ SỐ. Hai trạng thái này không được lẫn nhau.

CREATE TABLE IF NOT EXISTS public."RateProgramPrepaymentFees" (
  "Id"        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ProgramId" integer NOT NULL REFERENCES public."RatePrograms"("Id") ON DELETE CASCADE,
  "YearFrom"  integer NOT NULL CHECK ("YearFrom" >= 1),
  "YearTo"    integer CHECK ("YearTo" IS NULL OR "YearTo" >= "YearFrom"),
  "FeeRatio"  numeric CHECK ("FeeRatio" IS NULL OR ("FeeRatio" >= 0 AND "FeeRatio" <= 1)),
  "Note"      text,
  UNIQUE ("ProgramId", "YearFrom")
);


-- ---------------------------------------------------------------------
-- 4. MÃ RATE ID TRÊN FBE
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."RateProgramFbeCodes" (
  "Id"          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ProgramId"   integer NOT NULL REFERENCES public."RatePrograms"("Id") ON DELETE CASCADE,
  "Scope"       text    NOT NULL CHECK ("Scope" IN ('co_dinh_suot_thoi_gian_vay', 'co_dinh_ky_dau', 'data_udf')),
  "Applies"     text    NOT NULL,
  "RateIdCode"  text,
  "Description" text,
  "RateIdValue" text,
  "SortOrder"   integer NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_rateprogramfbecodes_program
  ON public."RateProgramFbeCodes" ("ProgramId", "SortOrder");


-- ---------------------------------------------------------------------
-- 5. THẨM QUYỀN ĐIỀU CHỈNH LÃI SUẤT TIỀN GỬI
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."DepositRateAuthorities" (
  "Id"             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ProgramId"      integer NOT NULL REFERENCES public."RatePrograms"("Id") ON DELETE CASCADE,
  "TenorLabel"     text    NOT NULL,
  "AuthorityLevel" text    NOT NULL,
  "CurrentRate"    numeric CHECK ("CurrentRate" IS NULL OR ("CurrentRate" >= 0 AND "CurrentRate" <= 1)),
  "AdjustedRate"   numeric CHECK ("AdjustedRate" IS NULL OR ("AdjustedRate" >= 0 AND "AdjustedRate" <= 1)),
  "SortOrder"      integer NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_depositrateauthorities_program
  ON public."DepositRateAuthorities" ("ProgramId", "SortOrder");


-- ---------------------------------------------------------------------
-- 6. RLS — mọi người đọc, chỉ admin ghi
-- ---------------------------------------------------------------------
-- Đây là tham số dùng chung toàn hệ thống, không phải dữ liệu khách hàng
-- nên không suy quyền theo OwnerId. Nhưng ghi sai một con số là chào sai
-- lãi cho toàn hệ thống, vì vậy quyền ghi giới hạn ở admin.

DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'RatePrograms', 'RateProgramTiers', 'RateProgramPrepaymentFees',
    'RateProgramFbeCodes', 'DepositRateAuthorities'
  ]
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);

    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || '_select', t);
    EXECUTE format(
      'CREATE POLICY %I ON public.%I FOR SELECT TO authenticated USING (true)',
      t || '_select', t
    );

    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || '_write', t);
    EXECUTE format(
      'CREATE POLICY %I ON public.%I FOR ALL TO authenticated USING (public.is_admin()) WITH CHECK (public.is_admin())',
      t || '_write', t
    );
  END LOOP;
END $$;


