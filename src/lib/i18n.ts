export type TranslationKey = keyof typeof dictionary.vi;

export function normalizeLang(raw: unknown): Lang {
  return raw === 'en' ? 'en' : 'vi';
}

export function loadLang(): Lang {
  return normalizeLang(localStorage.getItem(LANG_STORAGE_KEY));
}

export function translate(lang: Lang, key: TranslationKey, vars?: Record<string, string | number>): string {
  const text = dictionary[lang][key] ?? dictionary.vi[key] ?? key;
  if (!vars) return text;
  return Object.entries(vars).reduce(
    (acc, [k, v]) => acc.replace(`{${k}}`, String(v)),
    text as string
  );
}
