-- ---------------------------------------------------------------------
-- 1. BẢNG PHƯƠNG ÁN
-- ---------------------------------------------------------------------
-- Đối tượng là KHÁCH HÀNG CÁ NHÂN / HỘ KINH DOANH, không phải doanh
-- nghiệp. Vì vậy không có cột Vốn góp và Nguồn kinh phí & quỹ khác:
-- hai dòng đó vẫn xuất hiện trong phụ lục để giữ đúng bố cục, giá trị 0.
--
-- Bỏ Vốn góp cũng đồng thời sửa lỗi của file gốc: D27 = D18+D23+F24 cộng
-- một khoản mục NGUỒN VỐN vào TỔNG TÀI SẢN. Lỗi không lộ ra vì vốn chủ
-- sở hữu là số dư nên hai vế vẫn cân, nhưng tổng tài sản bị thổi lên
-- đúng bằng vốn góp.

CREATE TABLE IF NOT EXISTS public."BusinessPlans" (
  "Id"                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "CustomerId"        integer NOT NULL REFERENCES public."Customers"("Id") ON DELETE CASCADE,
  "CreditContractId"  integer REFERENCES public."CreditContracts"("Id") ON DELETE SET NULL,

  "PlanKind"          text NOT NULL DEFAULT 'limit'
                        CHECK ("PlanKind" IN ('limit', 'each_time')),
  "ActualYear"        integer NOT NULL,
  "PlanYear"          integer NOT NULL,
  "BalanceSheetDate"  date NOT NULL,

  -- Bảng cân đối — tài sản
  "Cash"                  numeric NOT NULL DEFAULT 0 CHECK ("Cash" >= 0),
  "Inventory"             numeric NOT NULL DEFAULT 0 CHECK ("Inventory" >= 0),
  "Receivables"           numeric NOT NULL DEFAULT 0 CHECK ("Receivables" >= 0),
  "OtherCurrentAssets"    numeric NOT NULL DEFAULT 0 CHECK ("OtherCurrentAssets" >= 0),
  "LongTermReceivables"   numeric NOT NULL DEFAULT 0 CHECK ("LongTermReceivables" >= 0),
  "FixedAssets"           numeric NOT NULL DEFAULT 0 CHECK ("FixedAssets" >= 0),
  "OtherLongTermAssets"   numeric NOT NULL DEFAULT 0 CHECK ("OtherLongTermAssets" >= 0),

  -- Bảng cân đối — nguồn vốn. Vốn tự có là SỐ DƯ, không phải ô nhập.
  "ShortTermDebt"         numeric NOT NULL DEFAULT 0 CHECK ("ShortTermDebt" >= 0),
  "OtherShortTermDebt"    numeric NOT NULL DEFAULT 0 CHECK ("OtherShortTermDebt" >= 0),
  "LongTermDebt"          numeric NOT NULL DEFAULT 0 CHECK ("LongTermDebt" >= 0),
  "OtherLongTermDebt"     numeric NOT NULL DEFAULT 0 CHECK ("OtherLongTermDebt" >= 0),

  -- Kết quả kinh doanh kỳ thực hiện
  "ActualRevenueAnnual"      numeric NOT NULL DEFAULT 0 CHECK ("ActualRevenueAnnual" >= 0),
  "ActualCogsRatioPercent"   numeric NOT NULL DEFAULT 0
                               CHECK ("ActualCogsRatioPercent" >= 0 AND "ActualCogsRatioPercent" <= 100),
  "ActualDepreciationAnnual" numeric NOT NULL DEFAULT 0 CHECK ("ActualDepreciationAnnual" >= 0),
  "ActualTaxAnnual"          numeric NOT NULL DEFAULT 0 CHECK ("ActualTaxAnnual" >= 0),
  "ActualStaffMonthly"       numeric NOT NULL DEFAULT 0 CHECK ("ActualStaffMonthly" >= 0),
  "ActualPremisesMonthly"    numeric NOT NULL DEFAULT 0 CHECK ("ActualPremisesMonthly" >= 0),
  "ActualUtilitiesMonthly"   numeric NOT NULL DEFAULT 0 CHECK ("ActualUtilitiesMonthly" >= 0),
  "ActualOtherMonthly"       numeric NOT NULL DEFAULT 0 CHECK ("ActualOtherMonthly" >= 0),

  -- Kết quả kinh doanh kỳ kế hoạch — ĐỦ TÁM Ô GIỐNG KỲ THỰC HIỆN.
  -- File gốc tính LNTT kế hoạch bằng E3-E4-E5-E6-J19-J21, bỏ sót chi phí
  -- mặt bằng và chi phí khác, nên lợi nhuận kế hoạch bị thổi lên. Cấu
  -- trúc đối xứng ở đây khiến lỗi đó không tái tạo được.
  "PlanRevenueAnnual"        numeric NOT NULL DEFAULT 0 CHECK ("PlanRevenueAnnual" >= 0),
  "PlanCogsRatioPercent"     numeric NOT NULL DEFAULT 0
                               CHECK ("PlanCogsRatioPercent" >= 0 AND "PlanCogsRatioPercent" <= 100),
  "PlanDepreciationAnnual"   numeric NOT NULL DEFAULT 0 CHECK ("PlanDepreciationAnnual" >= 0),
  "PlanTaxAnnual"            numeric NOT NULL DEFAULT 0 CHECK ("PlanTaxAnnual" >= 0),
  "PlanStaffMonthly"         numeric NOT NULL DEFAULT 0 CHECK ("PlanStaffMonthly" >= 0),
  "PlanPremisesMonthly"      numeric NOT NULL DEFAULT 0 CHECK ("PlanPremisesMonthly" >= 0),
  "PlanUtilitiesMonthly"     numeric NOT NULL DEFAULT 0 CHECK ("PlanUtilitiesMonthly" >= 0),
  "PlanOtherMonthly"         numeric NOT NULL DEFAULT 0 CHECK ("PlanOtherMonthly" >= 0),

  -- Đề nghị cấp hạn mức (chế độ 'limit')
  "RequestedLimitActual"     numeric NOT NULL DEFAULT 0 CHECK ("RequestedLimitActual" >= 0),
  "RequestedLimitPlan"       numeric NOT NULL DEFAULT 0 CHECK ("RequestedLimitPlan" >= 0),

  -- Thu chi hộ gia đình (chế độ 'each_time'). Thẩm định cá nhân bắt buộc
  -- có phần này; bảng Excel gốc không có vì vốn dựng cho hộ kinh doanh.
  "OtherIncomeMonthly"        numeric NOT NULL DEFAULT 0 CHECK ("OtherIncomeMonthly" >= 0),
  "LivingExpenseMonthly"      numeric NOT NULL DEFAULT 0 CHECK ("LivingExpenseMonthly" >= 0),
  "ExistingDebtPaymentMonthly" numeric NOT NULL DEFAULT 0 CHECK ("ExistingDebtPaymentMonthly" >= 0),
  "MaxDtiPercent"             numeric NOT NULL DEFAULT 0
                                CHECK ("MaxDtiPercent" >= 0 AND "MaxDtiPercent" <= 100),

  -- Phương án vay từng lần
  "ProjectCost"        numeric NOT NULL DEFAULT 0 CHECK ("ProjectCost" >= 0),
  "OwnFunds"           numeric NOT NULL DEFAULT 0 CHECK ("OwnFunds" >= 0),
  "TenorMonths"        integer NOT NULL DEFAULT 0 CHECK ("TenorMonths" >= 0),
  "RateAnnualPercent"  numeric NOT NULL DEFAULT 0 CHECK ("RateAnnualPercent" >= 0),

  -- Diễn giải cột "Cơ sở xác định" của phụ lục KET QUA KINH DOANH.
  -- Đây là phần tốn công nhất khi làm hồ sơ nên phải lưu, mỗi dòng một cột.
  "BasisRevenue"       text,
  "BasisCogs"          text,
  "BasisStaff"         text,
  "BasisPremises"      text,
  "BasisUtilities"     text,
  "BasisInterest"      text,
  "BasisDepreciation"  text,
  "BasisOther"         text,
  "BasisTax"           text,
  "BasisProfit"        text,

  "Note"        text,
  "CreatedBy"   uuid REFERENCES auth.users(id),
  "CreatedAt"   timestamptz NOT NULL DEFAULT now(),
  "UpdatedAt"   timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT "BusinessPlans_plan_year_sau_actual" CHECK ("PlanYear" >= "ActualYear")
);

COMMENT ON TABLE public."BusinessPlans" IS
  'Bảng tính phương án kinh doanh và hạn mức cho khách hàng cá nhân / hộ kinh doanh. Chỉ lưu ô đầu vào; số dẫn xuất tính bằng computeBusinessPlan trong src/lib/businessPlan.ts.';

COMMENT ON COLUMN public."BusinessPlans"."PlanKind" IS
  'limit = cấp hạn mức tín dụng (xuất đủ ba phụ lục). each_time = cho vay từng lần (không có khối nhu cầu vốn lưu động, xuất hai phụ lục).';

COMMENT ON COLUMN public."BusinessPlans"."MaxDtiPercent" IS
  'Trần tỷ lệ nghĩa vụ trả nợ trên thu nhập. Bằng 0 nghĩa là CHƯA KHAI, và khi đó khả năng vay theo dòng tiền trả về 0 chứ không suy đoán.';

-- Khả năng bảo đảm của tài sản KHÔNG có cột ở đây. Con số đó tính bằng
-- usableCapacity từ chính TSĐB của khách hàng và thay đổi khi định giá
-- hết hiệu lực; lưu lại là tạo bản sao đóng băng, đúng kiểu sai lầm mà
-- ba phụ lục Excel đang mắc phải.

COMMENT ON COLUMN public."BusinessPlans"."ActualCogsRatioPercent" IS
  'Tỷ lệ giá vốn trên doanh thu. Doanh thu là ô nhập, vòng quay vốn lưu động là kết quả tính ra — không làm ngược như công thức D3 = D10*3,4 của file gốc.';


-- ---------------------------------------------------------------------
-- 2. DƯ NỢ ĐANG CÓ VÀ KHOẢN ĐỀ NGHỊ CẤP MỚI
-- ---------------------------------------------------------------------
-- File gốc cố định ba dòng (VB hiện hữu, VB cấp mới, TCTD khác) và nhúng
-- cứng lãi suất 8%/năm trong công thức *8/100/12. Ở đây mỗi khoản một
-- dòng với lãi suất riêng, lấy gợi ý từ chương trình lãi suất đang hiệu
-- lực trong hệ thống.
--
-- Đây là NGUỒN DUY NHẤT của chi phí lãi vay. File gốc có hai con số lãi
-- vay không khớp nhau: D6 tính từ bảng dư nợ ra 48 trđ, còn dòng lãi vay
-- trong bảng chi phí để 0 nhập tay — lợi nhuận trình lên bị sai lệch
-- đúng bằng khoảng cách đó.

CREATE TABLE IF NOT EXISTS public."BusinessPlanDebts" (
  "Id"                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "PlanId"             integer NOT NULL REFERENCES public."BusinessPlans"("Id") ON DELETE CASCADE,
  "Label"              text    NOT NULL,
  "Principal"          numeric NOT NULL DEFAULT 0 CHECK ("Principal" >= 0),
  "RateAnnualPercent"  numeric NOT NULL DEFAULT 0 CHECK ("RateAnnualPercent" >= 0),
  "Scope"              text    NOT NULL DEFAULT 'both' CHECK ("Scope" IN ('both', 'plan')),
  "SortOrder"          integer NOT NULL DEFAULT 0,
  "CreatedAt"          timestamptz NOT NULL DEFAULT now()
);

COMMENT ON COLUMN public."BusinessPlanDebts"."Scope" IS
  'both = khoản đang có, tính lãi cho cả kỳ thực hiện và kỳ kế hoạch. plan = khoản đề nghị cấp mới, chỉ tính lãi cho kỳ kế hoạch.';

CREATE INDEX IF NOT EXISTS idx_bp_customer   ON public."BusinessPlans" ("CustomerId", "CreatedAt" DESC);
CREATE INDEX IF NOT EXISTS idx_bp_hdtd       ON public."BusinessPlans" ("CreditContractId");
CREATE INDEX IF NOT EXISTS idx_bp_debts_plan ON public."BusinessPlanDebts" ("PlanId", "SortOrder");


-- ---------------------------------------------------------------------
-- 3. MỐC SỬA ĐỔI
-- ---------------------------------------------------------------------
-- Đặt ở trigger thay vì để ứng dụng tự ghi: quên một đường ghi là mốc sai.

CREATE OR REPLACE FUNCTION public.touch_business_plan_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW."UpdatedAt" := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_business_plan_updated_at ON public."BusinessPlans";
CREATE TRIGGER trg_business_plan_updated_at
  BEFORE UPDATE ON public."BusinessPlans"
  FOR EACH ROW EXECUTE FUNCTION public.touch_business_plan_updated_at();


-- ---------------------------------------------------------------------
-- 4. HÀM PHÂN QUYỀN CHO DÒNG DƯ NỢ
-- ---------------------------------------------------------------------
-- Quyền suy theo quan hệ tới khách hàng, giống mọi bảng con khác.

CREATE OR REPLACE FUNCTION public.can_access_business_plan(plan_id integer)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
  SELECT public.is_admin() OR EXISTS (
    SELECT 1
    FROM public."BusinessPlans" bp
    JOIN public."Customers" c ON c."Id" = bp."CustomerId"
    WHERE bp."Id" = plan_id AND c."OwnerId" = auth.uid()
  );
$$;


-- ---------------------------------------------------------------------
-- 5. ROW LEVEL SECURITY
-- ---------------------------------------------------------------------
ALTER TABLE public."BusinessPlans"     ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."BusinessPlanDebts" ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "business_plans_all" ON public."BusinessPlans";
CREATE POLICY "business_plans_all" ON public."BusinessPlans"
  FOR ALL TO authenticated
  USING (public.can_access_customer("CustomerId"))
  WITH CHECK (public.can_access_customer("CustomerId"));

DROP POLICY IF EXISTS "business_plan_debts_all" ON public."BusinessPlanDebts";
CREATE POLICY "business_plan_debts_all" ON public."BusinessPlanDebts"
  FOR ALL TO authenticated
  USING (public.can_access_business_plan("PlanId"))
  WITH CHECK (public.can_access_business_plan("PlanId"));

REVOKE ALL ON public."BusinessPlans"     FROM anon;
REVOKE ALL ON public."BusinessPlanDebts" FROM anon;

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;


