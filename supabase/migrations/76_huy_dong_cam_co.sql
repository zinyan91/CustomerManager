CREATE OR REPLACE FUNCTION public.can_access_pledge_loan(p_pledge_loan_id bigint)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public."PledgeLoans" l
    WHERE l."Id" = p_pledge_loan_id AND public.can_access_customer(l."CustomerId")
  );
$$;

CREATE POLICY "savings_books_all" ON public."SavingsBooks"
  FOR ALL TO authenticated
  USING (public.can_access_customer("CustomerId"))
  WITH CHECK (public.can_access_customer("CustomerId"));

CREATE POLICY "pledge_loans_all" ON public."PledgeLoans"
  FOR ALL TO authenticated
  USING (public.can_access_customer("CustomerId"))
  WITH CHECK (public.can_access_customer("CustomerId"));

CREATE POLICY "pledge_loan_savings_books_all" ON public."PledgeLoanSavingsBooks"
  FOR ALL TO authenticated
  USING (public.can_access_pledge_loan("PledgeLoanId"))
  WITH CHECK (public.can_access_pledge_loan("PledgeLoanId"));

CREATE POLICY "pledge_loan_repayments_all" ON public."PledgeLoanRepayments"
  FOR ALL TO authenticated
  USING (public.can_access_pledge_loan("PledgeLoanId"))
  WITH CHECK (public.can_access_pledge_loan("PledgeLoanId"));

REVOKE ALL ON public."SavingsBooks"           FROM anon;
REVOKE ALL ON public."PledgeLoans"            FROM anon;
REVOKE ALL ON public."PledgeLoanSavingsBooks" FROM anon;
REVOKE ALL ON public."PledgeLoanRepayments"   FROM anon;

