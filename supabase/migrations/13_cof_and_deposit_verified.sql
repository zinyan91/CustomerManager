-- ---------------------------------------------------------------------
-- 2. CHƯƠNG TRÌNH MUA BÁN VỐN NỘI BỘ
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."CofPrograms" (
  "Id"               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "Name"             text    NOT NULL,
  "DocumentNumber"   text    NOT NULL UNIQUE,
  "DocumentDate"     date,
  "EffectiveFrom"    date    NOT NULL,
  "EffectiveTo"      date,
  "ReplacesDocument" text,
  "SourceVerified"   boolean NOT NULL DEFAULT false,
  "Note"             text,
  "CreatedAt"        timestamptz NOT NULL DEFAULT now(),
  "UpdatedAt"        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_cofprograms_period
    CHECK ("EffectiveTo" IS NULL OR "EffectiveTo" >= "EffectiveFrom")
);

COMMENT ON TABLE public."CofPrograms" IS
  'Bảng giá mua vốn từ Hội Sở (FTP bán - COF) theo từng thời kỳ.';

-- Ma trận kỳ hạn × kỳ điều chỉnh lãi suất. Để dạng BẢNG RỘNG, mỗi kỳ hạn
-- một dòng, vì đó đúng hình dạng bảng trong văn bản và là dạng admin sửa
-- được nhanh nhất. NULL = ô trống trong văn bản, KHÔNG phải 0%.
CREATE TABLE IF NOT EXISTS public."CofStandardRates" (
  "Id"          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ProgramId"   integer NOT NULL REFERENCES public."CofPrograms"("Id") ON DELETE CASCADE,
  "Section"     text    NOT NULL,
  "TenorLabel"  text    NOT NULL,
  "FixedRate"   numeric CHECK ("FixedRate"   IS NULL OR ("FixedRate"   >= 0 AND "FixedRate"   <= 1)),
  "Reset3M"     numeric CHECK ("Reset3M"     IS NULL OR ("Reset3M"     >= 0 AND "Reset3M"     <= 1)),
  "Reset6M"     numeric CHECK ("Reset6M"     IS NULL OR ("Reset6M"     >= 0 AND "Reset6M"     <= 1)),
  "Reset9M"     numeric CHECK ("Reset9M"     IS NULL OR ("Reset9M"     >= 0 AND "Reset9M"     <= 1)),
  "Reset12M"    numeric CHECK ("Reset12M"    IS NULL OR ("Reset12M"    >= 0 AND "Reset12M"    <= 1)),
  "Reset24M"    numeric CHECK ("Reset24M"    IS NULL OR ("Reset24M"    >= 0 AND "Reset24M"    <= 1)),
  "Reset36M"    numeric CHECK ("Reset36M"    IS NULL OR ("Reset36M"    >= 0 AND "Reset36M"    <= 1)),
  "SortOrder"   integer NOT NULL DEFAULT 0,
  UNIQUE ("ProgramId", "Section", "TenorLabel")
);

COMMENT ON COLUMN public."CofStandardRates"."FixedRate" IS
  'Cột LSCĐ — cố định lãi suất suốt thời gian vay. NULL nghĩa là văn bản bỏ trống ô đó, khác hẳn 0%.';

-- Các mục còn lại của Phụ lục B: sản phẩm đặc thù, nợ quá hạn, thanh
-- khoản, phần thu bổ sung khi tất toán trước hạn. Có mục là con số, có
-- mục là công thức bằng lời — nên tách hai cột thay vì nhét chung.
CREATE TABLE IF NOT EXISTS public."CofRateItems" (
  "Id"         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ProgramId"  integer NOT NULL REFERENCES public."CofPrograms"("Id") ON DELETE CASCADE,
  "Section"    text    NOT NULL,
  "GroupLabel" text,
  "Label"      text    NOT NULL,
  "RateAnnual" numeric CHECK ("RateAnnual" IS NULL OR ("RateAnnual" >= 0 AND "RateAnnual" <= 1)),
  "Formula"    text,
  "Note"       text,
  "SortOrder"  integer NOT NULL DEFAULT 0
);

COMMENT ON COLUMN public."CofRateItems"."Formula" IS
  'Dùng khi văn bản quy định bằng công thức chứ không bằng con số, ví dụ "Lãi suất cho vay - 0,75%/năm".';

CREATE INDEX IF NOT EXISTS idx_cofstandardrates_program
  ON public."CofStandardRates" ("ProgramId", "Section", "SortOrder");
CREATE INDEX IF NOT EXISTS idx_cofrateitems_program
  ON public."CofRateItems" ("ProgramId", "Section", "SortOrder");


-- ---------------------------------------------------------------------
-- 3. RLS — mọi người đọc, chỉ admin ghi
-- ---------------------------------------------------------------------

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['CofPrograms', 'CofStandardRates', 'CofRateItems']
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || '_select', t);
    EXECUTE format(
      'CREATE POLICY %I ON public.%I FOR SELECT TO authenticated USING (true)',
      t || '_select', t);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || '_write', t);
    EXECUTE format(
      'CREATE POLICY %I ON public.%I FOR ALL TO authenticated USING (public.is_admin()) WITH CHECK (public.is_admin())',
      t || '_write', t);
  END LOOP;
END $$;


