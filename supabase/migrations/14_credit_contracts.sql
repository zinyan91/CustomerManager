-- =====================================================================
-- Tách Hợp đồng Tín dụng (HĐTD) thành thực thể riêng
-- =====================================================================
-- Trước đây mỗi dòng "LoanContracts" là một KUNN, và số HĐTD không phải
-- một trường dữ liệu mà được SUY RA từ chuỗi: bóc từ Note nếu có "HĐTD:",
-- ngược lại cắt phần trước "/GNN-". Ba hệ quả:
--
--   1. Không nhập được HĐTD đã ký mà chưa giải ngân, vì HĐTD chỉ tồn tại
--      khi có ít nhất một dòng KUNN.
--   2. HMTD còn hiệu lực nhưng đã tất toán hết KUNN thì biến mất khỏi
--      giao diện, dù vẫn được giải ngân tiếp.
--   3. Thông tin cấp HĐTD (tổng mức cấp, ngày hiệu lực) lặp trên từng
--      dòng KUNN và trôi dạt âm thầm; code đang che bằng cách lấy giá trị
--      lớn nhất trong nhóm.
--
-- An toàn khi chạy lại nhiều lần.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. HÀM SUY SỐ HĐTD TỪ DỮ LIỆU CŨ
-- ---------------------------------------------------------------------
-- Cài ĐÚNG một lần rồi dùng lại ở cả hai bước dưới. Viết lặp biểu thức
-- này ở hai chỗ là cách chắc chắn nhất để chúng lệch nhau về sau.
-- Giữ khớp với getMasterHdtdNumber trong src/lib/utils.ts.

CREATE OR REPLACE FUNCTION public.hdtd_number_of(contract_number text, note text)
RETURNS text
LANGUAGE sql IMMUTABLE
AS $$
  SELECT COALESCE(
    NULLIF(btrim(substring(note FROM 'HĐTD:[[:space:]]*([^' || chr(10) || chr(13) || ']+)')), ''),
    NULLIF(btrim(split_part(contract_number, '/GNN-', 1)), ''),
    NULLIF(btrim(contract_number), ''),
    'HĐTD-CHÍNH'
  );
$$;


-- ---------------------------------------------------------------------
-- 2. BẢNG HỢP ĐỒNG TÍN DỤNG
-- ---------------------------------------------------------------------
-- Số HĐTD duy nhất TRONG TỪNG KHÁCH HÀNG, không duy nhất toàn hệ thống:
-- hồ sơ cũ dùng dải số riêng (PNAT...) nên không áp được định dạng chung.

CREATE TABLE IF NOT EXISTS public."CreditContracts" (
  "Id"                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "CustomerId"               integer NOT NULL REFERENCES public."Customers"("Id") ON DELETE CASCADE,
  "HdtdNumber"               text    NOT NULL,

  "ApprovalCode"             text,
  "ApprovalAmount"           numeric,

  "LoanMethod"               text,
  "ContractAmount"           numeric,
  "ContractStartDate"        date,
  "ContractEndDate"          date,
  "LoanTenorMonths"          integer,

  "LoanPurpose"              text,
  "LoanPurposeType"          text,

  "PreferentialRate"         numeric,
  "PreferentialPeriodMonths" integer,
  "PostPreferentialRate"     numeric,
  "BaseRate"                 numeric,
  "MarginRate"               numeric,
  "NormalRate"               numeric,
  "InterestRate"             numeric,
  "RateHistory"              text,

  "CollateralIds"            text,

  "IsClosed"                 boolean NOT NULL DEFAULT false,
  "ClosedDate"               date,
  "Note"                     text,
  "CreatedAt"                timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT uq_credit_contract_number UNIQUE ("CustomerId", "HdtdNumber")
);

COMMENT ON TABLE public."CreditContracts" IS
  'Hợp đồng tín dụng. Một dòng một hợp đồng. Tồn tại độc lập với KUNN ở cả hai đầu: đã ký chưa giải ngân, và đã tất toán hết KUNN nhưng hạn mức còn hiệu lực.';

COMMENT ON COLUMN public."CreditContracts"."ApprovalCode" IS
  'Mã hạn mức được duyệt. Nhiều HĐTD dùng chung một mã thì hạn mức chỉ tính MỘT lần. Không phải số hợp đồng.';

COMMENT ON COLUMN public."CreditContracts"."CollateralIds" IS
  'TSBĐ bảo đảm cho hợp đồng. KUNN thừa hưởng, không gán lại từng lần giải ngân.';

CREATE INDEX IF NOT EXISTS idx_credit_contracts_customer
  ON public."CreditContracts" ("CustomerId");

CREATE INDEX IF NOT EXISTS idx_credit_contracts_approval
  ON public."CreditContracts" ("ApprovalCode")
  WHERE "ApprovalCode" IS NOT NULL;


