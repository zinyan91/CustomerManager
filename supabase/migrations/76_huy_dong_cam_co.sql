CREATE TABLE "SavingsBooks" (
  "Id"                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "CustomerId"            bigint  NOT NULL REFERENCES "Customers"("Id") ON DELETE RESTRICT,
  "BookNumber"            text    NOT NULL,
  "DepositType"           text    NOT NULL DEFAULT 'tg_vnd',
  "Currency"              text    NOT NULL DEFAULT 'VND',
  "ExchangeRate"          numeric,
  "Amount"                numeric NOT NULL,
  "InterestRate"          numeric,
  "OpenDate"              date,
  "Tenor"                 integer,
  "TenorUnit"             text,
  "MaturityDate"          date,
  "InterestPaymentMethod" text    NOT NULL DEFAULT 'end_term',
  "PaidInterest"          numeric NOT NULL DEFAULT 0,
  "IsClosed"              boolean NOT NULL DEFAULT false,
  "ClosedDate"            date,
  "ClosingInterest"       numeric,
  "MovedFromCollateralId" bigint,
  "Note"                  text,
  "CreatedAt"             timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT "SavingsBooks_LoaiTienGui_hop_le" CHECK ("DepositType" IN ('tg_vnd', 'tg_foreign', 'cctg')),
  CONSTRAINT "SavingsBooks_DonViKyHan_hop_le" CHECK ("TenorUnit" IS NULL OR "TenorUnit" IN ('thang', 'nam', 'tuan', 'ngay')),
  CONSTRAINT "SavingsBooks_LanhLai_hop_le" CHECK ("InterestPaymentMethod" IN ('end_term', 'periodic', 'upfront')),
  CONSTRAINT "SavingsBooks_SoTien_duong" CHECK ("Amount" > 0),
  CONSTRAINT "SavingsBooks_LaiDaChi_khong_am" CHECK ("PaidInterest" >= 0),
  CONSTRAINT "SavingsBooks_KyHan_duong" CHECK ("Tenor" IS NULL OR "Tenor" > 0),
  CONSTRAINT "SavingsBooks_TyGia_duong" CHECK ("ExchangeRate" IS NULL OR "ExchangeRate" > 0)
);
CREATE UNIQUE INDEX "SavingsBooks_BookNumber_key" ON "SavingsBooks" (lower(btrim("BookNumber")));
CREATE INDEX "SavingsBooks_CustomerId_idx" ON "SavingsBooks" ("CustomerId");

CREATE TABLE "PledgeLoans" (
  "Id"                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "CustomerId"             bigint  NOT NULL REFERENCES "Customers"("Id") ON DELETE RESTRICT,
  "ContractNumber"         text    NOT NULL,
  "Amount"                 numeric NOT NULL,
  "InterestRate"           numeric NOT NULL,
  "DisbursementDate"       date    NOT NULL,
  "DueDate"                date    NOT NULL,
  "LoanPurpose"            text,
  "IsClosed"               boolean NOT NULL DEFAULT false,
  "ClosedDate"             date,
  "ClosedHow"              text,
  "LegacyCreditContractId" bigint,
  "LegacyLoanContractId"   bigint,
  "Note"                   text,
  "CreatedAt"              timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT "PledgeLoans_SoTien_duong" CHECK ("Amount" > 0),
  CONSTRAINT "PledgeLoans_LaiSuat_khong_am" CHECK ("InterestRate" >= 0),
  CONSTRAINT "PledgeLoans_DenHan_sau_GiaiNgan" CHECK ("DueDate" > "DisbursementDate"),
  CONSTRAINT "PledgeLoans_CachTatToan_hop_le" CHECK ("ClosedHow" IS NULL OR "ClosedHow" IN ('partial', 'full', 'due', 'offset'))
);
CREATE UNIQUE INDEX "PledgeLoans_ContractNumber_key" ON "PledgeLoans" (lower(btrim("ContractNumber")));
CREATE INDEX "PledgeLoans_CustomerId_idx" ON "PledgeLoans" ("CustomerId");

CREATE TABLE "PledgeLoanSavingsBooks" (
  "Id"               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "PledgeLoanId"     bigint  NOT NULL REFERENCES "PledgeLoans"("Id") ON DELETE CASCADE,
  "SavingsBookId"    bigint  NOT NULL REFERENCES "SavingsBooks"("Id") ON DELETE RESTRICT,
  "PrincipalCovered" numeric NOT NULL,
  "ReleasedDate"     date,
  "Note"             text,

  CONSTRAINT "PledgeLoanSavingsBooks_GocBaoDam_khong_am" CHECK ("PrincipalCovered" >= 0),
  CONSTRAINT "PledgeLoanSavingsBooks_duy_nhat" UNIQUE ("PledgeLoanId", "SavingsBookId")
);
CREATE INDEX "PledgeLoanSavingsBooks_SavingsBookId_idx" ON "PledgeLoanSavingsBooks" ("SavingsBookId");

CREATE TABLE "PledgeLoanRepayments" (
  "Id"                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "PledgeLoanId"        bigint  NOT NULL REFERENCES "PledgeLoans"("Id") ON DELETE CASCADE,
  "RepaymentDate"       date    NOT NULL,
  "Kind"                text    NOT NULL,
  "PrincipalPaid"       numeric NOT NULL DEFAULT 0,
  "InterestPaid"        numeric NOT NULL DEFAULT 0,
  "PenaltyPaid"         numeric NOT NULL DEFAULT 0,
  "OffsetSavingsBookId" bigint REFERENCES "SavingsBooks"("Id") ON DELETE RESTRICT,
  "Note"                text,
  "CreatedAt"           timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT "PledgeLoanRepayments_Kind_hop_le" CHECK ("Kind" IN ('partial', 'full', 'due', 'offset')),
  CONSTRAINT "PledgeLoanRepayments_Tien_khong_am" CHECK ("PrincipalPaid" >= 0 AND "InterestPaid" >= 0 AND "PenaltyPaid" >= 0),
  CONSTRAINT "PledgeLoanRepayments_CanTru_phai_co_so" CHECK ("Kind" <> 'offset' OR "OffsetSavingsBookId" IS NOT NULL)
);
CREATE INDEX "PledgeLoanRepayments_PledgeLoanId_idx" ON "PledgeLoanRepayments" ("PledgeLoanId");

ALTER TABLE "SavingsBooks"
  ADD CONSTRAINT "SavingsBooks_MovedFromCollateralId_fkey"
