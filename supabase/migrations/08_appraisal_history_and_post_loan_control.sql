-- ---------------------------------------------------------------------
-- 1. LỊCH SỬ ĐỊNH GIÁ
-- ---------------------------------------------------------------------
-- Trước đây định giá lại GHI ĐÈ giá trị cũ trên bảng Collaterals, mất
-- lịch sử. Không so được biến động giá trị và xếp loại giữa các kỳ.

CREATE TABLE IF NOT EXISTS public."CollateralAppraisals" (
  "Id"             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "CollateralId"   integer NOT NULL REFERENCES public."Collaterals"("Id") ON DELETE CASCADE,
  "AppraisalDate"  date    NOT NULL,
  "TenorMonths"    integer NOT NULL DEFAULT 12 CHECK ("TenorMonths" IN (6, 12, 24)),
  "ExpiryDate"     date    GENERATED ALWAYS AS
                     (("AppraisalDate" + ("TenorMonths" * INTERVAL '1 month'))::date) STORED,
  "AppraisedValue" numeric NOT NULL CHECK ("AppraisedValue" >= 0),
  "AssetType"      text,
  "LtvPercent"     numeric NOT NULL CHECK ("LtvPercent" >= 0 AND "LtvPercent" <= 100),
  "PerformedBy"    uuid REFERENCES auth.users(id),
  "Note"           text,
  "CreatedAt"      timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public."CollateralAppraisals" IS
  'Lịch sử định giá TSĐB. Mỗi lần định giá một dòng. Bảng Collaterals giữ giá trị hiện hành, được trigger đồng bộ tự động.';

CREATE INDEX IF NOT EXISTS idx_appraisals_collateral
  ON public."CollateralAppraisals" ("CollateralId", "AppraisalDate" DESC);


-- ---------------------------------------------------------------------
-- 2. ĐỒNG BỘ GIÁ TRỊ HIỆN HÀNH VỀ BẢNG Collaterals
-- ---------------------------------------------------------------------
-- Dùng trigger thay vì để ứng dụng ghi hai nơi. Ứng dụng quên cập nhật
-- là hai bên lệch nhau, và lệch âm thầm.

CREATE OR REPLACE FUNCTION public.sync_collateral_latest_appraisal()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
DECLARE
  latest public."CollateralAppraisals";
BEGIN
  SELECT * INTO latest
  FROM public."CollateralAppraisals"
  WHERE "CollateralId" = COALESCE(NEW."CollateralId", OLD."CollateralId")
  ORDER BY "AppraisalDate" DESC, "Id" DESC
  LIMIT 1;

  IF latest."Id" IS NOT NULL THEN
    UPDATE public."Collaterals"
    SET "AppraisedValue"        = latest."AppraisedValue",
        "Value"                 = latest."AppraisedValue",
        "LtvPercent"            = latest."LtvPercent",
        "AssetType"             = COALESCE(latest."AssetType", "AssetType"),
        "AppraisalDate"         = latest."AppraisalDate",
        "AppraisalTenorMonths"  = latest."TenorMonths",
        "AppraisalExpiryDate"   = to_char(latest."ExpiryDate", 'YYYY-MM-DD')
    WHERE "Id" = latest."CollateralId";
  END IF;

  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_sync_collateral_appraisal ON public."CollateralAppraisals";
CREATE TRIGGER trg_sync_collateral_appraisal
  AFTER INSERT OR UPDATE OR DELETE ON public."CollateralAppraisals"
  FOR EACH ROW EXECUTE FUNCTION public.sync_collateral_latest_appraisal();


-- ---------------------------------------------------------------------
-- 3. NẠP LỊCH SỬ TỪ DỮ LIỆU HIỆN CÓ
-- ---------------------------------------------------------------------
-- Coi giá trị đang lưu trên Collaterals là lần định giá đầu tiên, để lịch
-- sử không bắt đầu từ số không. Chỉ nạp tài sản đã có ngày định giá.

INSERT INTO public."CollateralAppraisals"
  ("CollateralId", "AppraisalDate", "TenorMonths", "AppraisedValue", "AssetType", "LtvPercent", "Note")
SELECT col."Id",
       col."AppraisalDate"::date,
       CASE WHEN COALESCE(col."AppraisalTenorMonths", 12) IN (6, 12, 24)
            THEN col."AppraisalTenorMonths" ELSE 12 END,
       COALESCE(col."AppraisedValue", col."Value", 0),
       col."AssetType",
       COALESCE(col."LtvPercent", 0),
       'Nạp từ dữ liệu hiện có khi tạo bảng lịch sử'
FROM public."Collaterals" col
WHERE col."AppraisalDate" IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM public."CollateralAppraisals" a WHERE a."CollateralId" = col."Id"
  );


-- ---------------------------------------------------------------------
-- 4. KẾT QUẢ KIỂM SOÁT SAU VAY
-- ---------------------------------------------------------------------
-- Ba loại kiểm tra, mỗi loại có MỘT phạm vi tự nhiên nên không cần cột
-- danh sách:
--   purpose     -> một KUNN            (ContractId)
--   periodic    -> một HĐTD gốc        (MasterHdtd + CustomerId)
--   collateral  -> một tài sản         (CollateralId)
--
-- ControlKey là khoá do lõi sinh lịch tạo ra (src/lib/postLoanControl.ts),
-- dùng để khớp bản ghi đã thực hiện với đợt kiểm tra tương ứng.

CREATE TABLE IF NOT EXISTS public."PostLoanControlRecords" (
  "Id"            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ControlType"   text    NOT NULL CHECK ("ControlType" IN ('purpose', 'periodic', 'collateral')),
  "ControlKey"    text    NOT NULL UNIQUE,
  "CustomerId"    integer NOT NULL REFERENCES public."Customers"("Id") ON DELETE CASCADE,
  "ContractId"    integer REFERENCES public."LoanContracts"("Id") ON DELETE CASCADE,
  "MasterHdtd"    text,
  "CollateralId"  integer REFERENCES public."Collaterals"("Id") ON DELETE CASCADE,
  "PeriodIndex"   integer NOT NULL DEFAULT 1,
  "DueDate"       date    NOT NULL,
  "PerformedDate" date    NOT NULL,
  "PerformedBy"   uuid REFERENCES auth.users(id),
  "Result"        text    NOT NULL CHECK ("Result" IN ('pass', 'watch', 'fail')),
  "Findings"      text,
  "AppraisalId"   integer REFERENCES public."CollateralAppraisals"("Id") ON DELETE SET NULL,
  "CreatedAt"     timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public."PostLoanControlRecords" IS
  'Kết quả các đợt kiểm soát sau vay đã thực hiện. Lịch các đợt CẦN kiểm tra được sinh tự động từ hợp đồng và tài sản, không lưu trong bảng này.';

COMMENT ON COLUMN public."PostLoanControlRecords"."ControlKey" IS
  'Khoá đợt kiểm tra do lõi sinh lịch tạo, ví dụ purpose-1024 hoặc periodic-1::HD01-3. Dùng để khớp với đợt tương ứng.';

COMMENT ON COLUMN public."PostLoanControlRecords"."AppraisalId" IS
  'Bản ghi định giá phát sinh từ đợt kiểm tra hiện trạng tài sản, nếu có.';

CREATE INDEX IF NOT EXISTS idx_plc_customer   ON public."PostLoanControlRecords" ("CustomerId");
CREATE INDEX IF NOT EXISTS idx_plc_contract   ON public."PostLoanControlRecords" ("ContractId");
CREATE INDEX IF NOT EXISTS idx_plc_collateral ON public."PostLoanControlRecords" ("CollateralId");
CREATE INDEX IF NOT EXISTS idx_plc_due        ON public."PostLoanControlRecords" ("DueDate");


-- ---------------------------------------------------------------------
-- 5. HÀM PHÂN QUYỀN CHO TÀI SẢN
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.can_access_collateral(col_id integer)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
  SELECT public.is_admin() OR EXISTS (
    SELECT 1
    FROM public."Collaterals" col
    JOIN public."Customers" c ON c."Id" = col."CustomerId"
    WHERE col."Id" = col_id AND c."OwnerId" = auth.uid()
  );
$$;


-- ---------------------------------------------------------------------
-- 6. ROW LEVEL SECURITY
-- ---------------------------------------------------------------------
ALTER TABLE public."CollateralAppraisals"    ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."PostLoanControlRecords"  ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "appraisals_all" ON public."CollateralAppraisals";
CREATE POLICY "appraisals_all" ON public."CollateralAppraisals"
  FOR ALL TO authenticated
  USING (public.can_access_collateral("CollateralId"))
  WITH CHECK (public.can_access_collateral("CollateralId"));

DROP POLICY IF EXISTS "plc_all" ON public."PostLoanControlRecords";
CREATE POLICY "plc_all" ON public."PostLoanControlRecords"
  FOR ALL TO authenticated
  USING (public.can_access_customer("CustomerId"))
  WITH CHECK (public.can_access_customer("CustomerId"));

REVOKE ALL ON public."CollateralAppraisals"   FROM anon;
REVOKE ALL ON public."PostLoanControlRecords" FROM anon;

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;


