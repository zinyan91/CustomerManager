-- Huy động & Cầm cố: sổ tiết kiệm và khoản vay cầm cố sổ tiết kiệm tách khỏi HĐTD/KUNN/TSBĐ.
--
-- VÌ SAO BẢNG RIÊNG: khoản vay cầm cố STK là một hợp đồng kiêm luôn KUNN, thời hạn
-- tính theo NGÀY, gốc và lãi trả một lần cuối kỳ, không có lịch trả nợ. TSBĐ là sổ
-- tiết kiệm của chính ngân hàng, và một sổ có thể bảo đảm cho nhiều khoản vay, một
-- khoản vay có thể dùng nhiều sổ. Nhét vào CreditContracts/LoanContracts là dựng
-- bảng nửa rỗng và một lịch trả nợ giả. Thiết kế: docs/specs/2026-10-27-huy-dong-cam-co-design.md
--
-- DƯ NỢ KHÔNG LƯU: dư nợ = Amount − Σ PrincipalPaid; ngày tính lãi gần nhất = ngày
-- trả gần nhất. Lưu thêm cột dư nợ sẽ có lúc lệch với lịch sử trả nợ.
--
-- LÃI SUẤT lưu theo PHẦN TRĂM (6.5 = 6,5%/năm), cùng quy ước với LoanContracts.
--
-- Ghi khoản vay + liên kết, và ghi trả nợ + tất toán, đi qua hai hàm SECURITY INVOKER
-- để mỗi thao tác là một khối nguyên vẹn mà RLS vẫn áp.
--
-- Ba cột Moved* đánh dấu bản ghi cũ đã chuyển sang bảng mới (migration 77); tầng API
-- lọc bỏ chúng để dư nợ không bị đếm hai lần.

