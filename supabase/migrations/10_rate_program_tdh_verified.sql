    "UpdatedAt"            = now(),
    "Note"                 = 'Hết hiệu lực khi hết hạn mức 1.000 tỷ đồng. '
      || 'Thời gian cố định lãi suất kỳ đầu không vượt quá 1/2 thời gian cho vay theo từng giấy nhận nợ, làm tròn xuống khi lẻ tháng. '
      || 'Không đáp ứng điều kiện thẻ tín dụng: truy thu phần lãi suất ưu đãi 0,1%/năm từ ngày giải ngân tới ngày truy thu và cộng thêm 0,1%/năm cho thời gian ưu đãi còn lại. '
      || 'Miễn phí trả nợ trước hạn nếu khách hàng trả trong vòng 30 ngày trước thời điểm kết thúc khoản vay.'
  WHERE "Id" = pid;

  -- Gói cố định 03 tháng: 0%/năm là số liệu ĐÃ BIẾT, không phải ô trống.
  UPDATE public."RateProgramTiers"
     SET "RateAnnual" = 0,
         "Note"       = 'Ưu đãi 0%/năm trong 03 tháng đầu.'
   WHERE "ProgramId" = pid AND "FixedMonths" = 3;

  UPDATE public."RateProgramTiers"
     SET "RateAnnual" = 0.0850, "Note" = NULL
   WHERE "ProgramId" = pid AND "FixedMonths" = 6;

  UPDATE public."RateProgramTiers"
     SET "RateAnnual" = 0.0950, "Note" = NULL
   WHERE "ProgramId" = pid AND "FixedMonths" = 12;

  UPDATE public."RateProgramTiers"
     SET "RateAnnual" = 0.1050, "Note" = NULL
   WHERE "ProgramId" = pid AND "FixedMonths" = 24;

  UPDATE public."RateProgramTiers"
     SET "MinTenorMonths" = 60
   WHERE "ProgramId" = pid;

  -- Phí trả nợ trước hạn Năm 3 = 2%, lấp chỗ bảng tính để trống.
  UPDATE public."RateProgramPrepaymentFees"
     SET "FeeRatio" = 0.0200, "Note" = NULL
   WHERE "ProgramId" = pid AND "YearFrom" = 3;

  UPDATE public."RateProgramPrepaymentFees"
     SET "Note" = 'Miễn phí trả nợ trước hạn nếu trả trong vòng 30 ngày trước thời điểm kết thúc khoản vay.'
   WHERE "ProgramId" = pid AND "YearFrom" = 6;

  DELETE FROM public."RateProgramFeeOptions" WHERE "ProgramId" = pid;

  INSERT INTO public."RateProgramFeeOptions"
    ("ProgramId", "OptionLabel", "PackageGroup", "MinFeeRatio", "CounterFeeRatio", "Note", "SortOrder")
  VALUES
    (pid, 'Phương án 1', 'Gói cố định LSCV 24 tháng đầu', 0.0150, 0.0100,
     'Phí dịch vụ tại quầy và/hoặc phí tài khoản số đẹp tối thiểu bằng 1,00% dư nợ giải ngân lần này.', 1),
    (pid, 'Phương án 1', 'Các gói cố định LSCV còn lại', 0.0100, 0.0050,
     'Phí dịch vụ tại quầy và/hoặc phí tài khoản số đẹp tối thiểu bằng 0,50% dư nợ giải ngân lần này.', 2),
    (pid, 'Phương án 2', 'Gói cố định LSCV 24 tháng đầu', 0.0175, NULL,
     'Tất cả các phí dịch vụ tại Vietbank, ngoại trừ phí trả nợ trước hạn.', 3),
