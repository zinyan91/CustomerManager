import fs from 'node:fs';
import assert from 'node:assert/strict';
import { JSDOM, VirtualConsole } from 'jsdom';
const base = 'docs/superpowers/specs/';
const errors = [];
const console = new VirtualConsole();
console.on('jsdomError', error => errors.push(error.message));
const dom = new JSDOM(fs.readFileSync(base + '2026-10-16-mockup-kien-truc-giao-dien-moi.html', 'utf8'), {
  url: 'http://localhost/mockup', runScripts: 'outside-only', pretendToBeVisual: true, virtualConsole: console,
});
const w = dom.window, d = w.document;
w.HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', ''); };
w.HTMLDialogElement.prototype.close = function () { this.removeAttribute('open'); this.dispatchEvent(new w.Event('close')); };
for (const name of ['model', 'views', 'controller']) w.eval(fs.readFileSync(base + `architecture-mockup-${name}.js`, 'utf8'));
const M = w.MockupModel;
let checks = 0;
const check = (value, message) => { assert.ok(value, message); checks++; };
const click = selector => { assert.ok(d.querySelector(selector), selector); d.querySelector(selector).click(); };
const change = (id, value) => { d.getElementById(id).value = value; d.getElementById(id).dispatchEvent(new w.Event('change', { bubbles: true })); };
const tick = () => new Promise(resolve => w.setTimeout(resolve, 5));
for (const preset of Object.keys(M.presets)) for (const screen of M.visibleScreens(preset)) {
  const cid = M.isScoped(screen) ? '101' : null;
  const route = M.findRoute(M.pathFor(screen, cid));
  check(route?.screen === screen.id, `route roundtrip ${screen.id}`);
  check(route.customerId === cid, `scope roundtrip ${screen.id}`);
}
check(d.querySelector('h1').textContent === 'Bàn làm việc', 'landing');
check(!d.querySelector('iframe, table, #payment-dialog, .metric'), 'no replacement functional UI');
check(d.querySelector('#workspace a')?.href === M.liveUrlFor(M.getScreen('dashboard')), 'existing dashboard reference');
check(d.querySelector('#workspace a')?.target === '_blank', 'actual application opens separately');
await tick();
click('[data-group="credit"]');
check(d.querySelector('h1').textContent === 'Khách hàng', 'credit group landing');
click('[data-action="search"]');
d.getElementById('search-input').value = 'Nam Ha';
d.getElementById('search-input').dispatchEvent(new w.Event('input', { bubbles: true }));
click('#search-results [data-screen="profile"]');
check(d.getElementById('customer-context').textContent.includes('Thép Nam Hà'), 'customer context');
check(d.querySelector('#workspace a').href.endsWith('/customers'), 'sample customer IDs never sent to actual app');
click('#record-tabs [data-screen="credit-contracts"]');
check(w.location.hash === '#/customers/101/credit-contracts', 'contract navigation keeps customer');
click('#record-tabs [data-screen="loans"]');
check(w.location.hash === '#/customers/101/loans', 'loan navigation keeps customer');
change('customer-select', '102');
check(w.location.hash === '#/customers/102/loans', 'change customer keeps screen');
check(!d.querySelector('table, #payment-form'), 'no reconstructed loan UI');
change('layout', 'tabs');
check(d.getElementById('shell').classList.contains('tabs'), 'tabs layout');
click('[data-group="finance"]');
check(d.querySelector('h1').textContent === 'Báo cáo tài chính', 'tabs change destination');
check(!d.getElementById('customer-context').hidden, 'analysis context retained');
click('[data-group="system"]');
check(d.getElementById('customer-context').hidden, 'settings global scope');
change('permission', 'rates');
check(!d.querySelector('[data-group="credit"]'), 'restricted group hidden');
click('[data-group="finance"]');
check(d.querySelector('h1').textContent === 'Dự phóng TOI', 'first permitted destination');
check(!d.querySelector('#secondary [data-screen="corporate-financial"]'), 'restricted child hidden');
change('permission', 'dispatch');
check(d.querySelector('h1').textContent === 'Văn thư', 'permission fallback');
check(!d.querySelector('[data-screen="admin"]'), 'admin hidden');
check(M.search('Nam Ha', 'dispatch').length === 0, 'search respects permission');
check(M.search('Nam Ha', 'full').length === 1, 'accent insensitive search');
check(M.search('KUNN/2026/089', 'full')[0].customerId === '101', 'loan search destination');
change('permission', 'full');
d.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'k', ctrlKey: true, bubbles: true, cancelable: true }));
check(d.getElementById('search-dialog').open, 'Ctrl K opens search');
d.getElementById('search-input').value = '<img src=x onerror=alert(1)>';
d.getElementById('search-input').dispatchEvent(new w.Event('input', { bubbles: true }));
check(!d.querySelector('#search-results img'), 'query not injected');
check(d.getElementById('search-results').textContent.includes('Không tìm'), 'search empty state');
d.getElementById('search-dialog').close();
change('theme', 'dark');
check(d.documentElement.dataset.theme === 'dark', 'dark theme');
Object.defineProperty(w, 'innerWidth', { value: 390, writable: true });
w.dispatchEvent(new w.Event('resize'));
click('[data-group="credit"]');
check(d.getElementById('shell').classList.contains('menu-open'), 'mobile drawer opens');
d.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
check(!d.getElementById('shell').classList.contains('menu-open'), 'mobile Escape closes menu');
for (const screen of M.screens) {
  if (screen.scope === 'customer') continue;
  w.location.hash = M.pathFor(screen, null); await tick(); await tick();
  check(d.querySelector('h1').textContent === screen.label, `destination opens ${screen.id}`);
  check(d.querySelector('#workspace a').href === M.liveUrlFor(screen), `original screen link ${screen.id}`);
  check(!d.querySelector('#workspace table, #workspace input, #workspace form'), `no functional UI replacement ${screen.id}`);
}
w.location.hash = '/customers/101/loans'; await tick(); await tick();
w.location.hash = '/settings'; await tick(); await tick();
w.history.back(); await new Promise(resolve => w.setTimeout(resolve, 40));
check(d.querySelector('h1').textContent === M.getScreen('loans').label, 'browser Back restores screen');
check(d.getElementById('customer-select').value === '101', 'browser Back restores context');
check(errors.length === 0, errors.join('\n'));
globalThis.console.log(`${checks} checks passed; no JavaScript errors`);
dom.window.close();
