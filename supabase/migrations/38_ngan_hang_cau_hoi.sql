-- Ngân hàng câu hỏi ôn tập nghiệp vụ: bảng QuizQuestions.
--
-- VÌ SAO MỘT BẢNG, LỰA CHỌN ĐỂ TRONG jsonb: lựa chọn của một câu hỏi là dữ liệu
-- trình bày có thứ tự, không bao giờ được tra riêng, không bao giờ được nối tới
-- bảng khác. Tách thành QuizOptions thì mỗi lần đọc một câu phải nối bảng và mỗi
-- lần sửa phải xoá rồi ghi lại toàn bộ dòng con. Ràng buộc thật sự cần — "đáp án
-- đúng phải nằm trong danh sách lựa chọn" — đã chốt bằng trigger dưới đây, nên
-- tách bảng không mua thêm được gì.
--
-- SỐ LƯỢNG LỰA CHỌN KHÔNG CỐ ĐỊNH 4 và SỐ ĐÁP ÁN ĐÚNG KHÔNG CỐ ĐỊNH 1. Đo trên
-- 662 câu của quiz_bank.json ngày 10/08/2026: số lựa chọn phân bố 1 → 5 câu
-- (644 câu có 4, 8 câu có 5, 8 câu có 2, 1 câu có 3, 1 câu có 1); số đáp án đúng
-- phân bố 1 → 5 (639 câu một đáp án, 23 câu nhiều đáp án). Vì vậy ràng buộc chỉ
-- đòi "ít nhất một lựa chọn, ít nhất một đáp án đúng" — đặt sàn 4 lựa chọn là
-- khoá dữ liệu thật ra ngoài.
--
-- CHỐNG TRÙNG CÂU HỎI: trigger, không phải unique index. Bộ 662 câu đã dọn sẵn
-- CÓ 9 CỤM TRÙNG NỘI DUNG gồm 24 câu (15 bản dư). Chủ dự án chốt 10/08/2026 giữ
-- nguyên chúng và chỉ chặn câu thêm mới, nên unique index không dựng nổi (build
-- sẽ đổ ngay trên dữ liệu nạp vào). Trigger cho phép đường nạp dữ liệu gốc đi
-- qua đúng một lần bằng cờ phiên app.quiz_seed, còn mọi đường ghi khác đều chặn.
--
-- BA TRONG CHÍN CỤM CÓ ĐÁP ÁN ĐÚNG KHÁC NHAU trên cùng một câu hỏi:
-- (267, 272, 274, 283), (309, 325, 344, 345), (318, 343, 347). Đây không phải
-- trùng vô hại — ít nhất một bản trong mỗi cụm đang dạy sai. Tab hiển thị cảnh
-- báo trên từng cụm để người có thẩm quyền quyết, hệ thống không tự chọn bản nào.

BEGIN;

CREATE TABLE "QuizQuestions" (
  "Id"             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "QuestionText"   text NOT NULL,
  "Options"        jsonb NOT NULL,
  "CorrectAnswers" text[] NOT NULL,
  "Sources"        text[] NOT NULL DEFAULT '{}',
  "Topic"          text,
  "CreatedBy"      uuid REFERENCES auth.users(id),
  "CreatedAt"      timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT "QuizQuestions_NoiDung_khong_rong"
    CHECK (btrim("QuestionText") <> ''),

  CONSTRAINT "QuizQuestions_LuaChon_la_mang"
    CHECK (jsonb_typeof("Options") = 'array' AND jsonb_array_length("Options") >= 1),

  CONSTRAINT "QuizQuestions_PhaiCoDapAnDung"
    CHECK (array_length("CorrectAnswers", 1) >= 1)
);

COMMENT ON TABLE "QuizQuestions" IS
  'Ngân hàng câu hỏi ôn tập nghiệp vụ tín dụng. Dữ liệu tham chiếu dùng chung, KHÔNG gắn khách hàng nào — cùng loại với RatePrograms, không phải hồ sơ tín dụng.';
COMMENT ON COLUMN "QuizQuestions"."Options" IS
  'Mảng jsonb [{"id":"A","text":"..."}] có thứ tự. Số lựa chọn không cố định 4.';
COMMENT ON COLUMN "QuizQuestions"."CorrectAnswers" IS
  'Tập mã lựa chọn đúng. Một câu có thể nhiều đáp án đúng. Trigger dưới đây chốt tập này luôn là tập con của mã trong Options.';


-- Dạng chuẩn hoá dùng để so trùng: hạ chữ, gộp mọi khoảng trắng về một dấu cách,
-- cắt hai đầu. Cố ý KHÔNG bỏ dấu tiếng Việt — hai câu khác dấu là hai câu khác
-- nghĩa. Bản sao của hàm này trong mã nguồn là quizNormalizeText ở
-- src/lib/quizBank.ts; sửa một bên phải sửa bên kia, test khoá cả hai.
CREATE OR REPLACE FUNCTION public.quiz_normalize_text(p_text text)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT btrim(regexp_replace(lower(coalesce(p_text, '')), '\s+', ' ', 'g'));
$$;

CREATE INDEX "QuizQuestions_NoiDungChuanHoa_idx"
  ON "QuizQuestions" (public.quiz_normalize_text("QuestionText"));


CREATE OR REPLACE FUNCTION public."fn_kiem_tra_cau_hoi"()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  ma_lua_chon text[];
  thieu       text[];
  id_trung    bigint;
BEGIN
  SELECT array_agg(o->>'id' ORDER BY ord)
    INTO ma_lua_chon
    FROM jsonb_array_elements(NEW."Options") WITH ORDINALITY AS t(o, ord);

  IF ma_lua_chon IS NULL OR array_position(ma_lua_chon, NULL) IS NOT NULL THEN
    RAISE EXCEPTION 'Mỗi lựa chọn phải có mã (khoá "id").';
  END IF;

  IF array_length(ma_lua_chon, 1) <> (SELECT count(DISTINCT m) FROM unnest(ma_lua_chon) m) THEN
    RAISE EXCEPTION 'Mã lựa chọn bị lặp trong cùng một câu hỏi: %',
      array_to_string(ma_lua_chon, ', ');
  END IF;

  SELECT array_agg(d) INTO thieu
    FROM unnest(NEW."CorrectAnswers") d
   WHERE d <> ALL (ma_lua_chon);

  IF thieu IS NOT NULL THEN
    RAISE EXCEPTION 'Đáp án đúng % không nằm trong danh sách lựa chọn %',
      array_to_string(thieu, ', '), array_to_string(ma_lua_chon, ', ');
  END IF;

  -- Chống trùng. Cờ phiên app.quiz_seed chỉ được đường nạp dữ liệu gốc bật lên,
  -- vì bộ 662 câu vốn đã chứa 9 cụm trùng phải giữ nguyên.
  IF coalesce(current_setting('app.quiz_seed', true), '') <> 'on' THEN
    SELECT q."Id" INTO id_trung
      FROM public."QuizQuestions" q
     WHERE public.quiz_normalize_text(q."QuestionText")
         = public.quiz_normalize_text(NEW."QuestionText")
       AND q."Id" <> coalesce(NEW."Id", -1)
     LIMIT 1;

    IF id_trung IS NOT NULL THEN
      RAISE EXCEPTION 'Câu hỏi này đã có trong ngân hàng (Id=%).', id_trung
        USING ERRCODE = 'unique_violation';
    END IF;
  END IF;

  RETURN NEW;
END $$;

CREATE TRIGGER "trg_kiem_tra_cau_hoi"
  BEFORE INSERT OR UPDATE ON "QuizQuestions"
  FOR EACH ROW EXECUTE FUNCTION public."fn_kiem_tra_cau_hoi"();


-- Nạp bộ câu hỏi gốc. Chỉ chạy được khi bảng đang RỖNG, nên không có đường nạp
-- đè hay nạp hai lần. SECURITY DEFINER vì phải bật cờ bỏ qua chống trùng —
-- đường duy nhất được phép mang 9 cụm trùng có sẵn vào bảng.
CREATE OR REPLACE FUNCTION public.seed_quiz_bank(p_questions jsonb)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  so_dong integer;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM auth.users WHERE id = auth.uid()) THEN
    RAISE EXCEPTION 'Phải đăng nhập mới nạp được ngân hàng câu hỏi.';
  END IF;

  IF EXISTS (SELECT 1 FROM public."QuizQuestions") THEN
    RAISE EXCEPTION 'Ngân hàng câu hỏi đã có dữ liệu; hàm nạp chỉ chạy trên bảng rỗng.';
  END IF;

  IF jsonb_typeof(p_questions) <> 'array' THEN
    RAISE EXCEPTION 'Tham số phải là mảng jsonb các câu hỏi.';
  END IF;

  PERFORM set_config('app.quiz_seed', 'on', true);

  INSERT INTO public."QuizQuestions"
    ("QuestionText", "Options", "CorrectAnswers", "Sources", "Topic", "CreatedBy")
  SELECT
    q->>'question',
    q->'options',
    ARRAY(SELECT jsonb_array_elements_text(q->'correct_answers')),
    coalesce(ARRAY(SELECT jsonb_array_elements_text(q->'sources')), '{}'),
    q->>'topic',
    auth.uid()
  FROM jsonb_array_elements(p_questions) AS q;

  GET DIAGNOSTICS so_dong = ROW_COUNT;

  PERFORM set_config('app.quiz_seed', 'off', true);

  RETURN so_dong;
END $$;

REVOKE ALL ON FUNCTION public.seed_quiz_bank(jsonb) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.seed_quiz_bank(jsonb) TO authenticated;


ALTER TABLE public."QuizQuestions" ENABLE ROW LEVEL SECURITY;

-- Ngân hàng câu hỏi là kiến thức dùng chung: ai đăng nhập cũng đọc được và cũng
-- thêm được. Nhưng SỬA và XOÁ thì chỉ admin hoặc chính người đã thêm — để một
-- banker không xoá được câu của người khác.
DROP POLICY IF EXISTS "quiz_questions_select" ON public."QuizQuestions";
CREATE POLICY "quiz_questions_select" ON public."QuizQuestions"
  FOR SELECT TO authenticated
  USING (true);

DROP POLICY IF EXISTS "quiz_questions_insert" ON public."QuizQuestions";
CREATE POLICY "quiz_questions_insert" ON public."QuizQuestions"
  FOR INSERT TO authenticated
  WITH CHECK ("CreatedBy" IS NULL OR "CreatedBy" = auth.uid());

DROP POLICY IF EXISTS "quiz_questions_update" ON public."QuizQuestions";
CREATE POLICY "quiz_questions_update" ON public."QuizQuestions"
  FOR UPDATE TO authenticated
  USING (public.is_admin() OR "CreatedBy" = auth.uid())
  WITH CHECK (public.is_admin() OR "CreatedBy" = auth.uid());

DROP POLICY IF EXISTS "quiz_questions_delete" ON public."QuizQuestions";
CREATE POLICY "quiz_questions_delete" ON public."QuizQuestions"
  FOR DELETE TO authenticated
  USING (public.is_admin() OR "CreatedBy" = auth.uid());

REVOKE ALL ON public."QuizQuestions" FROM anon;

COMMIT;


-- Đối chiếu. Kỳ vọng: bảng tồn tại, RLS bật, đúng 4 policy, 0 bảng hở RLS.

SELECT c.relname AS bang, c.relrowsecurity AS rls_bat,
       (SELECT count(*) FROM pg_policies p
          WHERE p.schemaname = 'public' AND p.tablename = c.relname) AS so_policy
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public' AND c.relname = 'QuizQuestions';

SELECT c.relname AS bang_ho_rls
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public' AND c.relkind = 'r' AND NOT c.relrowsecurity
ORDER BY 1;

-- Sau khi nạp: kỳ vọng 662 dòng và 9 cụm trùng (24 câu) còn nguyên.
SELECT count(*) AS so_cau FROM "QuizQuestions";

SELECT count(*) AS so_cum_trung
FROM (
  SELECT public.quiz_normalize_text("QuestionText")
  FROM "QuizQuestions"
  GROUP BY 1 HAVING count(*) > 1
) t;
