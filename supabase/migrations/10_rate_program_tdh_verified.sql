-- Ba chỗ migration 09 ghi sai hoặc để trống, nay sửa:
--
--   1. Gói cố định 03 tháng: 09 để NULL vì tưởng bảng tính bỏ trống.
--      Thực tế LSCV của gói này ĐÚNG LÀ 0%/năm — đây là ưu đãi 0% ba
--      tháng đầu, không phải ô chưa điền. Ghi 0, không phải NULL.
--
--   2. Phí trả nợ trước hạn Năm 3: bảng tính nhảy từ Năm 2 sang Năm 4.
--      Văn bản quy định 2%.
--
--   3. Số văn bản, ngày hiệu lực và hạn mức chương trình: 09 chưa có.
--
-- Bổ sung bảng phí dịch vụ theo phương án, vì mức phí phụ thuộc đồng
-- thời vào phương án khách chọn và nhóm gói cố định — không nhét được
