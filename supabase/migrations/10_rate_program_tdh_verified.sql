-- ---------------------------------------------------------------------
-- 1. PHÍ DỊCH VỤ THEO PHƯƠNG ÁN
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."RateProgramFeeOptions" (
  "Id"            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ProgramId"     integer NOT NULL REFERENCES public."RatePrograms"("Id") ON DELETE CASCADE,
  "OptionLabel"   text    NOT NULL,
  "PackageGroup"  text    NOT NULL,
  "MinFeeRatio"   numeric CHECK ("MinFeeRatio" IS NULL OR ("MinFeeRatio" >= 0 AND "MinFeeRatio" <= 1)),
  "CounterFeeRatio" numeric CHECK ("CounterFeeRatio" IS NULL OR ("CounterFeeRatio" >= 0 AND "CounterFeeRatio" <= 1)),
  "Note"          text,
  "SortOrder"     integer NOT NULL DEFAULT 0
);

COMMENT ON COLUMN public."RateProgramFeeOptions"."CounterFeeRatio" IS
  'Phần phí tối thiểu phải phát sinh tại quầy và/hoặc phí tài khoản số đẹp. NULL = văn bản không tách riêng.';

CREATE INDEX IF NOT EXISTS idx_rateprogramfeeoptions_program
  ON public."RateProgramFeeOptions" ("ProgramId", "SortOrder");

ALTER TABLE public."RateProgramFeeOptions" ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "RateProgramFeeOptions_select" ON public."RateProgramFeeOptions";
CREATE POLICY "RateProgramFeeOptions_select"
  ON public."RateProgramFeeOptions" FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "RateProgramFeeOptions_write" ON public."RateProgramFeeOptions";
CREATE POLICY "RateProgramFeeOptions_write"
  ON public."RateProgramFeeOptions" FOR ALL TO authenticated
  USING (public.is_admin()) WITH CHECK (public.is_admin());


